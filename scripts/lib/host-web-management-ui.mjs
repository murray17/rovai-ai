import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

// Extends the existing actual Desktop/Web seam with production management
// actions. Native requests only observe outcomes; no Runtime is configured.
export async function exerciseBrowserManagement({ web, read, fixture, capture, openCamp, threadId }) {
  const button = (label, scope = 'document') => `[...${scope}.querySelectorAll('button')].find(e=>e.getClientRects().length>0 && e.textContent.trim()===${JSON.stringify(label)})`
  const click = async label => { await web.wait(`Boolean(${button(label)}) && !(${button(label)}).disabled`); await web.click(button(label)) }
  const fill = async (selector, text) => {
    await web.wait(`document.querySelector(${JSON.stringify(selector)})!==null`)
    await web.click(`document.querySelector(${JSON.stringify(selector)})`)
    await web.evaluate(`document.querySelector(${JSON.stringify(selector)}).select()`)
    await web.send('Input.insertText', { text })
  }
  await web.click(`document.querySelector('.rail-button[aria-label="记忆"]')`)
  await click('新增记忆')
  await fill('.memory-body-field textarea', 'Browser-created shared memory fixture.')
  await fill('.memory-body-field input', 'browser-fixture')
  await click('保存记忆')
  await web.wait(`document.querySelector('.app-dialog')===null`)
  const memory = (await read('memory.list')).memories.find(item => item.currentBody === 'Browser-created shared memory fixture.')
  assert.ok(memory, 'browser memory creation must persist in Core')
  await click('修订')
  await fill('.memory-body-field textarea', 'Browser-revised shared memory fixture.')
  await click('保存修订')
  await web.wait(`document.querySelector('.app-dialog')===null`)
  assert.equal((await read('memory.list')).memories.find(item=>item.id===memory.id).currentBody, 'Browser-revised shared memory fixture.')
  await click('停止沿用')
  await web.wait(`Boolean(${button('重新沿用')})`)
  assert.equal((await read('memory.list')).memories.find(item=>item.id===memory.id).lifecycle, 'retired')
  await capture('web-memory-management.png')

  await web.click(`document.querySelector('.rail-button[aria-label="队员"]')`)
  const member = (await read('members.list')).find(item=>item.presence==='present')
  const memberButton = `[...document.querySelectorAll('.member-sidebar-select')].find(e=>e.getAttribute('aria-label')?.startsWith(${JSON.stringify(member.displayName + '，')}))`
  await web.wait(`Boolean(${memberButton})`)
  await web.click(memberButton)
  await web.wait(`Boolean(document.querySelector('.member-portrait img')?.naturalWidth)`)
  await web.click(`document.querySelector('[aria-label="管理 ${member.displayName}"]')`)
  await web.click(`[...document.querySelectorAll('[role=menuitem]')].find(e=>e.textContent.trim()==='更换角色图片')`)
  await web.send('Page.setInterceptFileChooserDialog', { enabled: true })
  const avatarPath = join(fixture, 'browser-avatar.png')
  const png = await web.evaluate(`(()=>{const c=document.createElement('canvas');c.width=320;c.height=400;const context=c.getContext('2d');context.fillStyle='#327e92';context.fillRect(0,0,320,400);return c.toDataURL('image/png').split(',')[1]})()`)
  await writeFile(avatarPath, Buffer.from(png, 'base64'))
  await click('上传图片')
  await web.wait(`document.querySelector('body > input[type=file]')!==null`)
  await web.setFiles('body > input[type=file]', [avatarPath])
  await click('使用这张图片')
  await web.wait(`document.querySelector('[aria-label="保存队员信息"]:not(:disabled)')!==null`)
  await web.click(`document.querySelector('[aria-label="保存队员信息"]')`)
  await web.wait(`document.querySelector('[aria-label="保存队员信息"]').disabled`)
  let updatedMember
  for (let attempt = 0; attempt < 50; attempt++) {
    updatedMember = (await read('members.list')).find(item=>item.agentId===member.agentId)
    if (updatedMember?.avatarRef && updatedMember.avatarRef !== member.avatarRef) break
    await new Promise(resolve => setTimeout(resolve, 100))
  }
  assert.ok(updatedMember, 'managed member remains available after profile save')
  assert.notEqual(updatedMember.avatarRef, member.avatarRef, 'browser crop/upload/profile save must persist the managed avatar')
  assert.ok(updatedMember.avatarRef)
  await web.wait(`Boolean(document.querySelector('.member-portrait img')?.naturalWidth) || [...document.querySelectorAll('.member-avatar img')].some(e=>e.src.startsWith('blob:') && e.naturalWidth>0)`)
  await capture('web-member-avatar.png')

  await web.click(`document.querySelector('.rail-button[aria-label="定时任务"]')`)
  await click('新建')
  await fill('.automation-name-input', 'Browser management fixture')
  await fill('.automation-prompt-input', 'Isolated future schedule; do not run during acceptance.')
  await web.click(`document.querySelector('[aria-label="重复频率"]')`)
  await web.click(`[...document.querySelectorAll('[role=menuitemradio]')].find(e=>e.textContent==='自定义')`)
  // Annual future tick; close immediately after saving. No Run is created.
  const future = new Date(Date.now() + 7 * 86400_000)
  await fill('[aria-label="5 段 Cron 表达式"]', `0 0 ${future.getDate()} ${future.getMonth()+1} *`)
  await click('保存')
  await web.wait(`document.querySelector('[aria-label="Browser management fixture的操作"]')!==null`)
  const automation = (await read('automations.list', { status: 'all', limit: 50 })).automations.find(item=>item.name==='Browser management fixture')
  assert.ok(automation)
  await web.click(`document.querySelector('[aria-label="Browser management fixture的操作"]')`)
  await web.click(`[...document.querySelectorAll('[role=menuitem]')].find(e=>e.textContent.trim()==='关闭')`)
  await web.wait(`document.querySelector('.automation-row [aria-label="已关闭"]')!==null || document.querySelector('[aria-label="定时任务列表"] [aria-label="已关闭"]')!==null`)
  assert.equal((await read('automations.get', { automationId: automation.automationId })).enabled, false)
  await capture('web-automation-management.png')

  await web.click(`document.querySelector('.sidebar-settings-main')`)
  await web.click(`[...document.querySelectorAll('.settings-sidebar-menu button')].find(e=>e.textContent==='MCP')`)
  await web.wait(`document.querySelector('[aria-label="添加配置"]:not(:disabled)')!==null`)
  await web.click(`document.querySelector('[aria-label="添加配置"]')`)
  await fill('[aria-label="MCP 配置 JSON"]', JSON.stringify({ mcpServers: { 'browser-fixture': { command: '/usr/bin/true', args: [] } } }, null, 2))
  await click('添加 MCP')
  await web.wait(`[...document.querySelectorAll('.capability-detail-heading h2')].some(e=>e.getClientRects().length>0 && e.textContent==='browser-fixture')`)
  assert.ok((await read('mcp.config.get')).servers.some(item=>item.name==='browser-fixture'))
  await capture('web-mcp-management.png')

  const skillPath = join(fixture, 'browser-fixture')
  await mkdir(skillPath)
  await writeFile(join(skillPath, 'SKILL.md'), '---\nname: browser-fixture\ndescription: Isolated browser import acceptance.\n---\n\nOnly use this fixture during isolated acceptance.\n')
  await web.click(`[...document.querySelectorAll('.settings-sidebar-menu button')].find(e=>e.textContent==='Skills')`)
  await click('导入')
  await click('选择文件夹')
  await web.wait(`document.querySelector('[aria-label="输入完整路径"]:not(:disabled)')!==null`)
  await web.click(`document.querySelector('[aria-label="输入完整路径"]')`)
  await web.wait(`document.querySelector('#host-workspace-path:not(:disabled)')!==null`)
  await fill('#host-workspace-path', skillPath)
  await click('前往')
  await web.wait(`document.querySelector('[role=dialog] .primary-button:not(:disabled)')!==null`)
  await web.click(`document.querySelector('[role=dialog] .primary-button')`)
  await web.wait(`document.querySelector('.web-workspace-picker')===null`)
  await click('导入 Skill')
  await web.wait(`[...document.querySelectorAll('.capability-detail-heading h2')].some(e=>e.getClientRects().length>0 && e.textContent==='browser-fixture')`)
  assert.ok((await read('skills.list')).some(item=>item.name==='browser-fixture'))
  await capture('web-skill-management.png')
  await web.click(`document.querySelector('.settings-sidebar-back')`)
  await openCamp()
  await web.click(`document.querySelector('button[data-detail="tasks"]')`)
  await web.wait(`document.querySelector('.task-new-button:not(:disabled)')!==null`)
  await web.click(`document.querySelector('.task-new-button')`)
  await fill('.task-editor input', 'Browser-created durable task')
  await web.evaluate(`(()=>{const select=document.querySelector('.task-editor select');select.value=${JSON.stringify(member.agentId)};select.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await web.click(`document.querySelector('.task-submit')`)
  await web.wait(`document.querySelector('.task-editor-dialog')===null`)
  await web.wait(`document.querySelector('[aria-label="打开任务：Browser-created durable task"]')!==null`)
  await web.click(`document.querySelector('[aria-label="打开任务：Browser-created durable task"]')`)
  await web.wait(`[...document.querySelectorAll('.task-detail-actions button')].some(e=>e.getClientRects().length>0 && e.textContent==='编辑' && !e.disabled)`)
  await web.click(`[...document.querySelectorAll('.task-detail-actions button')].find(e=>e.textContent==='编辑')`)
  await fill('.task-editor input', 'Browser-updated durable task')
  await web.click(`document.querySelector('.task-submit')`)
  await web.wait(`document.querySelector('.task-editor-dialog')===null`)
  await web.wait(`document.querySelector('.task-detail h3')?.textContent==='Browser-updated durable task'`)
  const task = (await read('camps.open', { threadId, traceId: crypto.randomUUID() })).tasks.find(item=>item.title==='Browser-updated durable task')
  assert.ok(task && task.version > 1)
  await web.click(`document.querySelector('.task-cancel-action')`)
  await fill('.task-cancel-dialog textarea', 'Isolated acceptance complete.')
  await web.click(`document.querySelector('.task-cancel-dialog .danger-button')`)
  await web.wait(`document.querySelector('.task-cancel-dialog')===null`)
  await web.wait(`document.querySelector('.task-detail-status.state-cancelled')!==null`)
  assert.equal((await read('camps.open', { threadId, traceId: crypto.randomUUID() })).tasks.find(item=>item.taskId===task.taskId).status, 'cancelled')
  await capture('web-task-management.png')
  await web.click(`document.querySelector('[aria-label="收起会话详情"]')`)
}
