const assert = require('node:assert/strict')

module.exports = async ({ run, click, key, settle, capture, window }) => {
  const choose = async (path) => {
    const currentPath = await run("document.querySelector('.skill-file-current').getAttribute('aria-label')")
    await click(currentPath)
    await click(path)
  }
  const search = async value => {
    await run(`(() => { const n=document.querySelector('[aria-label="查找文件"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(n,${JSON.stringify(value)}); n.dispatchEvent(new Event('input',{bubbles:true})) })()`)
    await settle()
  }
  assert.equal(await run("/\\br\\d+\\b/.test(document.querySelector('.capability-detail-header').innerText)"), false)
  await click('切换文件，当前 SKILL.md')
  assert.equal(await run("document.querySelectorAll('.skill-file-entry').length"), 12)
  assert.equal(await run("document.querySelectorAll('.skill-file-entry[aria-current=true] .skill-file-icon-check').length"), 1)
  assert.equal(await run("document.querySelectorAll('[role=dialog]').length"), 0, 'Files expand inside the reading pane')
  await capture('skill-files-day-open')
  const reads = await run("window.capabilityTest.requests.filter(r=>r.method==='skills.content.read').length")
  await search('guide.md')
  assert.equal(await run("document.querySelectorAll('.skill-file-entry').length"), 2, 'Same-named files retain their distinct parent paths')
  assert.ok(await run("[...document.querySelectorAll('.skill-file-search-path')].some(n=>n.textContent==='notes')"))
  await search('no-match')
  assert.equal(await run("document.querySelector('.skill-file-empty').textContent"), '没有匹配的文件。')
  assert.equal(await run("window.capabilityTest.requests.filter(r=>r.method==='skills.content.read').length"), reads, 'Searching never reads file bodies')
  await run("document.querySelector('[aria-label=\"查找文件\"]').focus()")
  await key('Escape')
  assert.equal(await run('document.activeElement.getAttribute("aria-label")'), '切换文件，当前 SKILL.md')
  await click('切换文件，当前 SKILL.md')
  assert.equal(await run("document.querySelector('[aria-label=\"查找文件\"]').value"), '')
  await key('Down')
  assert.equal(await run('document.activeElement.getAttribute("aria-label")'), 'SKILL.md')
  await click('references')
  assert.equal(await run("document.querySelector('[data-folder-path=references]').getAttribute('aria-expanded')"), 'false')
  await key('Right')
  assert.equal(await run("document.querySelector('[data-folder-path=references]').getAttribute('aria-expanded')"), 'true')
  await click('references/guide.md')
  assert.equal(await run("document.querySelector('.capability-reading').innerText"), '参考内容。')
  assert.equal(await run('document.activeElement.getAttribute("aria-label")'), '切换文件，当前 references/guide.md')
  assert.equal(await run("document.querySelectorAll('.skill-file-directory').length"), 0)
  assert.equal(await run("document.querySelector('.capability-detail-scroll').scrollTop"), 0)
  await click('源码')
  assert.equal(await run("document.querySelector('.capability-source-code').textContent"), '参考内容。')
  await choose('SKILL.md')
  await run("window.capabilityTest.holdContent('references/guide.md')")
  await choose('references/guide.md')
  assert.ok(await run("document.querySelector('.capability-empty').textContent.includes('正在读取')"))
  await choose('agents/openai.yaml')
  assert.equal(await run("document.querySelectorAll('.capability-view-modes').length"), 0)
  await run('window.capabilityTest.releaseContent()')
  await settle()
  assert.ok(await run("document.querySelector('.capability-source-code').textContent.includes('display_name')"), 'Late file reads cannot replace the new selection')
  await run("window.capabilityTest.holdContent('SKILL.md')")
  await choose('SKILL.md')
  await click('design-review')
  await run('window.capabilityTest.releaseContent()')
  await settle()
  assert.ok(await run("document.querySelector('.capability-reading').textContent.includes('单文件 Skill')"), 'A late response from another Skill cannot replace the active target')
  assert.equal(await run("document.querySelectorAll('button.skill-file-current').length"), 0, 'A single-file Skill needs no chooser')
  await click('ui-ux-pro-max')
  await run("window.capabilityTest.failContent('references/guide.md')")
  await choose('references/guide.md')
  assert.ok(await run("document.querySelector('.capability-error').textContent.includes('暂时无法读取')"))
  await click('重试')
  assert.ok(await run("document.querySelector('.capability-reading').textContent.includes('参考内容。')"))
  await choose('assets/icon.png')
  assert.ok(await run("document.querySelector('.skill-content-preview').textContent.includes('该文件不是文本文件')"))
  await choose('references/large.md')
  assert.ok(await run("document.querySelector('.skill-content-preview').textContent.includes('该文件较大')"))
  const longPath = await run('window.capabilityTest.longPreviewPath')
  await choose(longPath)
  for (const [width, height] of [[1040, 700], [2560, 1440]]) {
    window.setContentSize(width, height)
    await settle()
    assert.ok(await run("document.documentElement.scrollWidth<=innerWidth"))
    assert.ok(await run("document.querySelector('.skill-file-current').getBoundingClientRect().right <= document.querySelector('.capability-view-modes').getBoundingClientRect().left"))
    await capture(`skill-file-long-path-${width}`)
  }
  await choose('SKILL.md')
  await run("document.documentElement.dataset.theme='night'")
  await click('切换文件，当前 SKILL.md')
  await capture('skill-files-night-2560')
  await key('Escape')
  window.setContentSize(1040, 700)
  window.webContents.setZoomFactor(2)
  await settle()
  await click('切换文件，当前 SKILL.md')
  assert.ok(await run("document.documentElement.scrollWidth<=innerWidth"))
  await click('references/guide.md')
  await capture('skill-files-night-zoom')
  window.webContents.setZoomFactor(1)
  window.setContentSize(1440, 920)
  await run("document.documentElement.dataset.theme='day'")
  await choose('SKILL.md')
  await run("document.querySelector('.capability-detail-scroll').scrollTop=500")
  await settle()
  assert.ok(await run("(() => {const bar=document.querySelector('.skill-file-toolbar').getBoundingClientRect();const scroll=document.querySelector('.capability-detail-scroll').getBoundingClientRect();return bar.top>=scroll.top-2&&bar.bottom<scroll.bottom})()"), 'The compact file toolbar stays reachable during long reading')
  await run("document.querySelector('.capability-detail-scroll').scrollTop=0")
  await settle()
}
