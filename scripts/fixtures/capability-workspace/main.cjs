const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
// This fixture mounts production components against an in-memory bridge. No Core or Runtime runs.
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1440, height: 920, useContentSize: true, webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  const run = code => window.webContents.executeJavaScript(code, true)
  const settle = () => run('window.capabilityTest.settle()')
  const snapshot = async () => { await settle(); return run('window.capabilityTest.snapshot()') }
  const click = async label => {
    await run(`(() => { const b=[...document.querySelectorAll('button')].find(b=>b.getBoundingClientRect().width>0 && (b.textContent.trim().replace(/\\s+/g, ' ') === ${JSON.stringify(label)} || b.getAttribute('aria-label') === ${JSON.stringify(label)})); if(!b) throw Error('Missing button '+${JSON.stringify(label)}); b.click() })()`)
    return snapshot()
  }
  const edit = async text => { await run(`(() => { const n=[...document.querySelectorAll('textarea')].find(n=>n.getBoundingClientRect().width>0); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(n, ${JSON.stringify(text)}); n.dispatchEvent(new Event('input',{bubbles:true})) })()`); await settle() }
  const draft = () => run("[...document.querySelectorAll('textarea')].find(n=>n.getBoundingClientRect().width>0)?.value")
  const capture = async name => writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
  try {
    await window.loadFile(renderer)
    await run("localStorage.clear()")
    await new Promise(resolve => { window.webContents.once('did-finish-load', resolve); window.reload() })
    window.webContents.setZoomFactor(1)
    let state = await snapshot()
    assert.equal(state.background, 'rgb(255, 255, 255)')
    assert.ok(state.text.includes('界面设计与实现'))
    assert.equal(state.list.width, 280)
    assert.equal(state.dialogs, 0)
    assert.equal(state.checkboxes, 0)
    await run("document.querySelector('.capability-files').open=true; const f=[...document.querySelectorAll('.capability-files button')].find(n=>n.textContent==='references/guide.md'); f.focus(); f.click()")
    await settle()
    assert.ok((await snapshot()).text.includes('参考内容。'))
    assert.equal(await run('document.activeElement.textContent'), 'references/guide.md', 'File navigation preserves keyboard focus while content loads')
    await click('SKILL.md')
    await run("document.querySelector('.capability-files').open=false")
    await capture('skills-day-wide')
    await click('生效范围 全部 14 组')
    assert.ok(await run("document.querySelectorAll('.capability-group-choice .member-avatar').length > 0"))
    await click('清除选择')
    assert.ok((await snapshot()).text.includes('未选择'))
    await click('选择全部')
    await run('window.capabilityTest.holdToggle()')
    await click('停用 ui-ux-pro-max')
    const listsBeforeResume = await run("window.capabilityTest.requests.filter(r=>r.method==='skills.list').length")
    await click('MCP')
    await click('Skills')
    assert.equal(await run("window.capabilityTest.requests.filter(r=>r.method==='skills.list').length"), listsBeforeResume, 'A page resume must not overwrite a pending mutation with an old read')
    await run('window.capabilityTest.releaseToggle()')
    await settle()
    assert.ok((await snapshot()).text.includes('已停用'))
    await click('已停用')
    assert.equal(await run("[...document.querySelectorAll('.capability-workspace')].find(n=>n.getBoundingClientRect().width>0).querySelectorAll('[data-capability-item]').length"), 2)
    await click('全部')
    await click('＋ 添加')
    assert.ok((await snapshot()).text.includes('选择文件夹'))
    assert.equal(await run("document.querySelectorAll('input[placeholder*=路径]').length"), 0)
    await click('选择文件夹')
    assert.equal(await run('window.capabilityTest.folderSelections()'), 1)
    assert.ok((await snapshot()).text.includes('默认启用 · 全部投递组'))
    assert.equal(await run("document.querySelectorAll('.capability-draft').length"), 0, 'Skill import creates no list placeholder')
    await run('window.capabilityTest.cancelFolder()')
    const inspected = await run("window.capabilityTest.requests.filter(r=>r.method==='skills.import.inspect').length")
    await click('选择文件夹')
    assert.equal(await run("window.capabilityTest.requests.filter(r=>r.method==='skills.import.inspect').length"), inspected, 'Folder cancellation does not inspect a typed or stale path')
    assert.ok((await snapshot()).text.includes('new-folder-skill'))
    await capture('skills-import-day')
    await click('导入 Skill')
    assert.ok((await snapshot()).text.includes('new-folder-skill'))
    await click('MCP')
    state = await snapshot()
    assert.ok(state.text.includes('配置 JSON'))
    await capture('mcp-day-wide')
    const json = '{\n  "mcpServers": {"docs": {"command": "node", "args": ["draft.mjs"]}}\n}'
    await edit(json)
    // Native pointer drag must preserve the editor node and unsaved draft.
    const point = await run("(() => { const n=[...document.querySelectorAll('[role=separator]')].find(n=>n.getBoundingClientRect().width>0); const r=n.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+80)} })()")
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseMove', x: point.x + 65, y: point.y })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: point.x + 65, y: point.y, button: 'left', clickCount: 1 })
    state = await snapshot()
    assert.equal(state.list.width, 345)
    assert.equal(await draft(), json)
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
    assert.equal((await snapshot()).list.width, 353, 'Keyboard provides a drag alternative')
    await run("[...document.querySelectorAll('[role=separator]')].find(n=>n.getBoundingClientRect().width>0).dispatchEvent(new MouseEvent('dblclick',{bubbles:true}))")
    assert.equal((await snapshot()).list.width, 280, 'Double click restores the default')
    await click('Skills')
    await click('MCP')
    assert.notEqual(await draft(), json, 'Leaving the page discards unsaved edits')
    await edit(json)
    await run('window.capabilityTest.conflict()')
    await click('保存')
    assert.ok((await snapshot()).text.includes('配置已更新'))
    assert.equal(await draft(), json, 'CAS conflict preserves unsaved JSON')
    await click('保存')
    assert.ok((await snapshot()).text.includes('已保存'))
    const positions = await run("(() => { const heading=[...document.querySelectorAll('.capability-library-heading')].find(n=>n.getBoundingClientRect().width>0); const add=heading.querySelector('button'),imp=heading.querySelector('[aria-label=\"从本机导入 MCP\"]');return {add:add.getBoundingClientRect().y,import:imp.getBoundingClientRect().y} })()")
    assert.equal(positions.add, positions.import, 'Add and import share the left heading row')
    await click('从本机导入 MCP')
    assert.ok((await snapshot()).text.includes('local-tools'))
    assert.equal(await run("document.querySelectorAll('.capability-draft').length"), 0, 'Import creates no list placeholder')
    await click('＋ 添加')
    assert.equal(await run("document.querySelectorAll('.capability-import-items').length"), 0)
    await edit('discard-this-new-config')
    await click('从本机导入 MCP')
    await click('＋ 添加')
    assert.ok(!(await draft()).includes('discard-this-new-config'), 'A new add form starts fresh')
    await click('从本机导入 MCP')
    await run("document.querySelector('.capability-import-pick').click()")
    await settle()
    await capture('mcp-import-day')
    await click('配置')
    await capture('mcp-import-config-day')
    await click('收起')
    for (const theme of ['day', 'night']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`)
      for (const width of [1040, 1760]) {
        window.setContentSize(width, 920)
        await settle()
        await capture(`mcp-import-${theme}-${width}`)
      }
    }
    window.setContentSize(1440, 920)
    await run("document.documentElement.dataset.theme='day'")
    await settle()
    await click('导入 1 项')
    assert.ok((await snapshot()).text.includes('local-tools'))
    await click('＋ 添加')
    await edit('{secret-do-not-echo')
    await click('添加 MCP')
    const alert = await run("[...document.querySelectorAll('[role=alert]')].find(n=>n.getBoundingClientRect().width>0)?.innerText")
    assert.ok(alert.includes('JSON 格式不正确'))
    assert.ok(!alert.includes('secret-do-not-echo'))
    await edit('{"mcpServers":{"new-connection":{"command":"node"}}}')
    await click('添加 MCP')
    assert.ok((await snapshot()).text.includes('new-connection'))
    for (const theme of ['day', 'night']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`)
      for (const width of [1040, 2560]) {
        window.setContentSize(width, width === 1040 ? 700 : 1440)
        state = await snapshot()
        assert.equal(state.overflow, false)
        assert.ok(state.detail.width >= 360)
        await capture(`mcp-${theme}-${width}`)
      }
    }
    await click('Skills')
    window.setContentSize(1040, 700)
    await settle()
    await capture('skills-night-minimum')
    window.webContents.setZoomFactor(2)
    state = await snapshot()
    assert.equal(state.compact, 'true')
    assert.equal(state.overflow, false)
    await click('← 返回列表')
    assert.ok((await snapshot()).list.width > 0)
    await capture('skills-night-zoom')
    console.log(JSON.stringify({ ok: true }))
    window.destroy(); app.quit()
  } catch (error) { console.error(error); await capture('failure'); app.exit(1) }
}).catch(error => { console.error(error); app.exit(1) })
