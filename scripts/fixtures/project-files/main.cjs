const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { execFileSync } = require('node:child_process')
const { mkdirSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { pathToFileURL } = require('node:url')
const { app, BrowserWindow, ipcMain } = require('electron')
const [root, fixture] = process.argv.slice(2)
let data = join(fixture, 'data')
const workspace = join(fixture, 'project'), primaryKey = process.platform === 'darwin' ? 'meta' : 'control'
mkdirSync(join(workspace, 'src/deep'), { recursive: true })
writeFileSync(join(workspace, 'package.json'), '{"name":"project"}\n')
writeFileSync(join(workspace, 'README.md'), '# Project\n\nLocal development.\n')
writeFileSync(join(workspace, 'src/index.ts'), 'export const value = 1;\n')
writeFileSync(join(workspace, 'src/deep/hidden-search.ts'), 'export const found = true;\n')
writeFileSync(join(workspace, 'unknown.xyz'), Buffer.from([0, 1, 2, 3]))
app.setPath('userData', join(fixture, 'userData'))
app.setPath('sessionData', join(fixture, 'sessionData'))
let host, window, service, cleanupRuntimeRoot
app.whenReady().then(async () => {
  const { launchHost } = await import(pathToFileURL(join(root, 'scripts/lib/host-test-client.mjs')))
  const runtimeRoots = await import(pathToFileURL(join(root, 'scripts/lib/runtime-camp-files-root.mjs')))
  cleanupRuntimeRoot = () => runtimeRoots.removeEphemeralRuntimeCampFilesRoot(data)
  const binary = join(root, 'target/debug', process.platform === 'win32' ? 'rovai-host.exe' : 'rovai-host')
  if (process.platform === 'win32') data = JSON.parse(execFileSync(binary, ['--prepare-windows-data-root', join(fixture, 'formal')], { encoding: 'utf8' })).core
  host = launchHost(binary, [...runtimeRoots.coreDataDirectoryArguments(data), '--skill-library-root', join(data, 'skills'), '--mcp-config-path', join(data, 'mcp.json')], { cwd: root })
  await host.ready
  const profiles = await host.request('members.list')
  const binding = await host.request('workspaces.validate', { path: workspace })
  const created = await host.request('camps.create', { commandId: randomUUID(), name: 'Directory acceptance', workspace: binding, memberAgentIds: [profiles[0].agentId], defaultLeadAgentId: profiles[0].agentId, collaborationMode: 'peer' })
  assert.equal(created.status, 'applied', JSON.stringify(created))
  const threadId = created.payload.threadId
  const { FilePreviewService, CoreFilePreviewSourceAuthority } = require(join(fixture, 'service.cjs'))
  let systemOpens = 0
  const native = { selectRoot: async () => null, confirmOpen: async () => false, openPath: async () => { systemOpens++; return '' }, revealPath() {}, copyText() {}, publishExternalUpdate: (id, event) => { if (window && !window.isDestroyed()) window.webContents.send('file-update', event) } }
  service = new FilePreviewService(new CoreFilePreviewSourceAuthority(host), native)
  window = new BrowserWindow({ width: 1540, height: 920, show: false, useContentSize: true, webPreferences: { preload: join(root, 'scripts/fixtures/project-files/preload.cjs'), sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => { if (event.level === 'error') console.error(event.message) })
  ipcMain.handle('thread', () => threadId)
  ipcMain.handle('project-files', (_event, request) => host.request('projectFiles.request', request))
  ipcMain.handle('files', async (_event, action, request) => {
    if (action === 'readEditableFile' || action === 'saveTextFile') return service.editText(window.webContents.id, request, action === 'saveTextFile')
    return service[action](window.webContents.id, request)
  })
  await window.loadFile(join(fixture, 'ui/index.html'))
  const run = code => window.webContents.executeJavaScript(code, true)
  const waitFor = async (condition, label = condition) => {
    for (let i = 0; i < 160; i++) { if (await run(condition)) return; await new Promise(resolve => setTimeout(resolve, 50)) }
    throw new Error(`Timed out: ${label}`)
  }
  const click = selector => run(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const rect = selector => run(`(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height}})()`)
  const row = name => `.project-files-row[title="${name}"]`
  const cases = []
  await waitFor('!!document.querySelector(".project-files-toggle")')
  const trigger = await rect('.project-files-toggle')
  assert.equal(await run('!!document.querySelector("#project-files-pane")'), false)
  await click('.project-files-toggle')
  await waitFor(`!!document.querySelector(${JSON.stringify(row('package.json'))})`)
  assert.equal((await run('window.projectFilesTest.state()')).visible, false, 'directory alone creates no empty preview')
  cases.push('directory-only')
  await click('.project-files-project')
  assert.equal(await run('!!document.querySelector("#project-files-pane")'), false)
  await click('.project-files-project')
  await waitFor(`!!document.querySelector(${JSON.stringify(row('package.json'))})`)
  await click(row('package.json'))
  await waitFor('!!document.querySelector(".file-preview-retained-host:not([hidden]) .cm-content")')
  assert.ok(await run('!!document.querySelector("#project-files-pane")'))
  const preview = await rect('.file-preview-retained-host:not([hidden])')
  const directory = await rect('#project-files-pane')
  assert.ok(preview.x + preview.width <= directory.x + 2, 'content is left of the tree')
  assert.equal((await rect('.project-files-toggle')).x, trigger.x)
  cases.push('shared-entry-and-preview')
  window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(directory.x), y: Math.round(directory.y + 100) })
  window.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, x: Math.round(directory.x), y: Math.round(directory.y + 100) })
  for (let offset = 10; offset <= 80; offset += 10) window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(directory.x - offset), y: Math.round(directory.y + 100) })
  window.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', x: Math.round(directory.x - 80), y: Math.round(directory.y + 100) })
  await new Promise(resolve => setTimeout(resolve, 200))
  assert.ok(Math.abs((await rect('.file-preview-retained-host:not([hidden])')).width - preview.width) < 2, 'directory drag must not resize sidecar')
  assert.ok((await rect('#project-files-pane')).width > directory.width, 'native splitter enlarges tree')
  cases.push('independent-resize')
  await click('.file-preview-toggle[aria-controls="file-preview-pane"]')
  assert.equal((await run('window.projectFilesTest.state()')).visible, false)
  assert.equal(await run('!!document.querySelector("#project-files-pane")'), true)
  await click(row('README.md'))
  await waitFor('!!document.querySelector(".file-preview-markdown-document")')
  await run('window.projectFilesTest.closeAll()')
  assert.equal(await run('!!document.querySelector("#project-files-pane")'), true)
  cases.push('sidecar-and-last-tab-independent')
  await run('(() => { const input=document.querySelector(".project-files-search input"); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,"value").set.call(input,"hidden-search"); input.dispatchEvent(new Event("input",{bubbles:true})); })()')
  await waitFor(`!!document.querySelector(${JSON.stringify(row('src/deep/hidden-search.ts'))})`)
  await click(row('src/deep/hidden-search.ts'))
  await waitFor('document.querySelector(".cm-content")?.textContent.includes("found")')
  cases.push('host-search-unexpanded')
  writeFileSync(join(workspace, 'new-visible.ts'), 'const changed = true;')
  await click('.project-files-search button')
  await waitFor(`!!document.querySelector(${JSON.stringify(row('new-visible.ts'))})`)
  await click(row('unknown.xyz'))
  await waitFor('document.querySelector(".file-preview-unavailable")?.textContent.includes("unknown.xyz")')
  assert.equal(systemOpens, 0, 'browsing an unsupported file does not launch an application')
  cases.push('external-change-and-unsupported')
  await click(row('package.json'))
  await waitFor('document.querySelector(".cm-content")?.textContent.includes("project")')
  writeFileSync(join(fixture, 'light.png'), (await window.webContents.capturePage()).toPNG())
  await run('window.fixtureTheme("night")')
  await new Promise(resolve => setTimeout(resolve, 100))
  writeFileSync(join(fixture, 'dark.png'), (await window.webContents.capturePage()).toPNG())
  window.setContentSize(720, 820)
  await waitFor('!!document.querySelector(".project-files-pane.is-drawer")')
  await click(row('src'))
  await waitFor(`!!document.querySelector(${JSON.stringify(row('src/index.ts'))})`)
  await click(row('src/index.ts'))
  await waitFor('!document.querySelector("#project-files-pane") && !!document.querySelector(".cm-content")')
  assert.equal(await run('document.querySelector("textarea").value'), '下一步检查移动端布局')
  await click('.project-files-toggle')
  await waitFor(`!!document.querySelector(${JSON.stringify(row('src/index.ts'))})`)
  writeFileSync(join(fixture, 'narrow.png'), (await window.webContents.capturePage()).toPNG())
  cases.push('narrow-drawer-preserves-navigation-and-draft')
  await run('window.fixtureEnglish()')
  await new Promise(resolve => setTimeout(resolve, 200))
  const englishControls = await rect('.file-preview-toggle-group')
  assert.ok(englishControls.x + englishControls.width <= 721, JSON.stringify(englishControls))
  assert.ok(await run(`['.project-files-toggle','.file-preview-toggle[aria-controls="file-preview-pane"]'].every(selector => { const button=document.querySelector(selector),r=button.getBoundingClientRect();return r.width >= 28 && button.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)) })`), 'English narrow controls remain visible and clickable')
  assert.ok(await run('document.querySelector(".project-files-search input").placeholder === "Search files"'))
  writeFileSync(join(fixture, 'english.png'), (await window.webContents.capturePage()).toPNG())
  await run('document.querySelector(".project-files-search input").focus()')
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
  await waitFor('!document.querySelector("#project-files-pane") && document.activeElement.classList.contains("project-files-toggle")')
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'P', modifiers: [primaryKey] }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'P', modifiers: [primaryKey] })
  await waitFor('!!document.querySelector(".project-files-quick")')
  assert.equal(await run('!!document.querySelector("#project-files-pane")'), false, 'quick open does not require the directory')
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
  await waitFor('!document.querySelector(".project-files-quick")')
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'E', modifiers: [primaryKey, 'shift'] }); window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'E', modifiers: [primaryKey, 'shift'] })
  await waitFor('!!document.querySelector("#project-files-pane")')
  cases.push('keyboard-shortcuts-focus-and-english')
  window.setContentSize(1440, 920); window.webContents.setZoomFactor(2)
  await new Promise(resolve => setTimeout(resolve, 150))
  assert.ok(await run('document.documentElement.scrollWidth <= innerWidth + 1'), '200% zoom has no page overflow')
  assert.ok(await run(`(() => {const b=document.querySelector('.project-files-toggle'),r=b.getBoundingClientRect();return r.width>=28 && b.contains(document.elementFromPoint(r.x+14,r.y+14))})()`))
  writeFileSync(join(fixture, 'zoom-200.png'), (await window.webContents.capturePage()).toPNG())
  cases.push('zoom-200')
  console.log(JSON.stringify({ ok: true, cases, screenshots: fixture }))
  await service.closeAll(); window.destroy(); await host.close(); await cleanupRuntimeRoot(); app.exit(0)
}).catch(async error => {
  console.error(error.stack)
  if (window && !window.isDestroyed()) writeFileSync(join(fixture, 'failure.png'), (await window.webContents.capturePage()).toPNG())
  await service?.closeAll().catch(() => {}); await host?.close(); await cleanupRuntimeRoot?.().catch(() => {}); app.exit(1)
})
