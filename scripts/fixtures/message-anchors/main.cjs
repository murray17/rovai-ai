const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData, evidence] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData) && isAbsolute(evidence))
mkdirSync(userData, { recursive: true })
mkdirSync(evidence, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: true, width: 1440, height: 920, useContentSize: true,
    title: 'Rovai message anchor acceptance', webPreferences: {
      contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false
    } })
  const errors = []
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  const run = code => window.webContents.executeJavaScript(code, true)
  const state = async () => { await run('window.anchorsTest.settle()'); return run('window.anchorsTest.snapshot()') }
  const key = async keyCode => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode })
    if (keyCode === 'Enter') window.webContents.sendInputEvent({ type: 'char', keyCode: '\r' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode })
    return state()
  }
  const move = async point => {
    window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(point.x), y: Math.round(point.y) })
    await new Promise(resolve => setTimeout(resolve, 180))
    return state()
  }
  const capture = async name => writeFileSync(join(evidence, `${name}.png`), (await window.webContents.capturePage()).toPNG())
  const checks = []
  const check = async (name, fn) => { await fn(); checks.push(name) }
  try {
    await window.loadFile(renderer)
    window.focus(); window.webContents.focus()
    await run('window.anchorsTest.settle()')
    await check('body mounts before the single index request and entry preview does not prefetch', async () => {
      assert.equal((await state()).requests.includes('thread.messages.anchors'), false)
      assert.ok((await run('window.anchorsTest.loadedIds()')).length > 0)
      await run('window.anchorsTest.bodyReady()')
      assert.equal((await state()).requests.filter(method => method === 'thread.messages.anchors').length, 1)
      assert.deepEqual(await run('window.anchorsTest.indexBodyMounted()'), [true])
    })
    await run('window.anchorsTest.top()')
    await check('four user messages enable the rail, teammate replies never count', async () => {
      await run('window.anchorsTest.count(3)')
      assert.equal((await state()).markers.length, 0)
      await run('window.anchorsTest.count(4)')
      const snapshot = await state()
      assert.equal(snapshot.markers.length, 4)
      assert.equal(snapshot.height, 40)
      assert.equal(snapshot.gutter, '60px')
      assert.ok(snapshot.markers.every(marker => marker.label.includes('/4')))
    })
    await run('window.anchorsTest.count(12); window.anchorsTest.top()')
    await check('all visible users are dark and all unhovered ticks remain equally short', async () => {
      const snapshot = await state()
      assert.ok(snapshot.markers.filter(marker => marker.current).length >= 2)
      assert.ok(snapshot.markers.every(marker => marker.width === 6))
      assert.ok(new Set(snapshot.markers.filter(marker => marker.current).map(marker => marker.color)).size === 1)
      await capture('01-compact-ticks')
    })
    await check('native hover alone lengthens its marker and previews the first reply in both themes', async () => {
      for (const theme of ['day', 'night']) {
        await run(`window.anchorsTest.theme('${theme}')`)
        await move({ x: 600, y: 40 })
        const snapshot = await move(await run('window.anchorsTest.firstMarker()'))
        assert.equal(snapshot.markers[0].width, 12)
        assert.ok(snapshot.markers.slice(1).every(marker => marker.width === 6))
        assert.equal(snapshot.title, await run('window.anchorsTest.longTitle'))
        assert.equal(snapshot.reply, await run('window.anchorsTest.firstReply'))
        assert.equal(snapshot.titleStyle.whiteSpace, 'nowrap')
        assert.equal(snapshot.titleStyle.overflow, 'ellipsis')
        assert.equal(snapshot.replyStyle.lines, '3')
        assert.notEqual(snapshot.titleStyle.color, snapshot.replyStyle.color)
        await capture(`02-preview-${theme}`)
      }
      const snapshot = await move({ x: 600, y: 40 })
      assert.ok(snapshot.markers.every(marker => marker.width === 6))
      assert.equal(snapshot.title, null)
    })
    await check('transparent action rows do not make the preceding user visible', async () => {
      await run('window.anchorsTest.actionOnly()')
      assert.equal((await state()).markers[0].current, null)
    })
    await check('narrow actual panes hide the rail and gutter, preserving keyboard focus', async () => {
      await run('window.anchorsTest.read("user-5")')
      const before = await run('window.anchorsTest.reading()')
      await run('window.anchorsTest.focus(); window.anchorsTest.width(759)')
      const snapshot = await state()
      assert.equal(snapshot.markers.length, 0)
      assert.equal(snapshot.gutter, '27px')
      assert.equal(await run("document.activeElement.classList.contains('camp-timeline')"), true)
      await run('window.anchorsTest.width(760)')
      assert.equal((await state()).markers.length, 12)
      await run('window.anchorsTest.width(undefined)')
      const after = await run('window.anchorsTest.reading()')
      assert.equal(after.id, before.id)
      assert.ok(Math.abs(after.top - before.top) < 1, `resize preserves reading: ${JSON.stringify({ before, after })}`)
    })
    await check('240 individual anchors remain height-bounded and their wheel does not move the transcript', async () => {
      await run('window.anchorsTest.theme("day"); window.anchorsTest.count(240)')
      await run('window.anchorsTest.top(); window.anchorsTest.railTop()')
      const before = await state()
      assert.equal(before.markers.length, 240)
      assert.equal(before.height, 360)
      assert.equal(before.navArrows, 0)
      const point = await run('window.anchorsTest.railPoint()')
      await move(point)
      window.webContents.sendInputEvent({ type: 'mouseWheel', x: Math.round(point.x), y: Math.round(point.y), deltaY: -500, deltaX: 0 })
      const after = await state()
      assert.ok(after.railTop > before.railTop, `native wheel scrolls the rail: ${JSON.stringify(after)}`)
      assert.equal(after.scrollTop, before.scrollTop)
      await capture('03-240-user-messages')
    })
    await check('keyboard can reach the last user and absent direct replies leave only the title', async () => {
      await move({ x: 600, y: 40 })
      await run('window.anchorsTest.focus()')
      const end = await key('End')
      assert.equal(end.focusedAnchor, 'user-240')
      assert.ok(end.markers.every(marker => marker.width === 6))
      assert.equal(end.title, '第 240 个问题：确认阅读位置与会话交互。')
      assert.equal(end.reply, null)
      await key('Escape')
      assert.equal((await state()).title, null)
      await run('document.documentElement.dataset.motionPreference = "reduce"')
      const located = await key('Enter')
      assert.equal(located.focusedMessage, 'user-240')
      assert.ok(located.markers.filter(marker => marker.current).some(marker => marker.id === 'user-240'))
      assert.equal(located.title, null)
    })
    await check('background replies preserve the draft and historical reading; a user input adds one marker', async () => {
      await run('window.anchorsTest.read("user-120"); window.anchorsTest.draft("保留的输入草稿")')
      const before = await state()
      await run('window.anchorsTest.appendAgent()')
      const after = await state()
      assert.equal(after.markers.length, 240)
      assert.equal(after.scrollTop, before.scrollTop)
      assert.equal(after.draft, before.draft)
      await run('window.anchorsTest.appendUser()')
      const appended = await state()
      assert.equal(appended.markers.length, 241)
      assert.equal(appended.draft, before.draft)
    })
    await check('history prepend leaves the complete index unchanged and preserves reading', async () => {
      await run('window.anchorsTest.count(240, 21)')
      assert.equal((await state()).markers.length, 260)
      await run('window.anchorsTest.read("user-80")')
      const before = await run('window.anchorsTest.reading()')
      await run('window.anchorsTest.loadEarlier()')
      const after = await run('window.anchorsTest.reading()')
      assert.equal((await state()).markers.length, 260)
      assert.equal(after.id, before.id)
      assert.ok(Math.abs(after.top - before.top) < 1, `${JSON.stringify({ before, after })}`)
    })
    await check('the minimum desktop window keeps a longer height-bounded rail and the composer reachable', async () => {
      window.setContentSize(1040, 700)
      const snapshot = await state()
      assert.equal(snapshot.markers.length, 260)
      assert.ok(snapshot.height > 250 && snapshot.height <= 360)
      assert.equal(await run("document.querySelector('[contenteditable=true]').getBoundingClientRect().bottom < innerHeight"), true)
      await capture('04-minimum-window')
      window.setContentSize(1440, 920)
      await state()
    })
    await check('200% zoom hides the narrow rail and reduced motion removes its transitions', async () => {
      assert.equal(await run("getComputedStyle(document.querySelector('.conversation-anchor-mark')).transitionDuration"), '0s')
      window.webContents.setZoomFactor(2)
      assert.equal((await state()).markers.length, 0)
      window.webContents.setZoomFactor(1)
      assert.equal((await state()).markers.length, 260)
    })
    await check('unloaded anchors use one bounded window and the normal loader stays with its own interval', async () => {
      await run('window.anchorsTest.count(20, 981)')
      const opened = await state()
      assert.equal(opened.markers.length, 1000)
      assert.ok(!(await run('window.anchorsTest.loadedIds()')).includes('user-100'))
      const indexes = opened.requests.filter(method => method === 'thread.messages.anchors').length
      await run('window.anchorsTest.runtimeEvent()')
      assert.equal((await state()).requests.filter(method => method === 'thread.messages.anchors').length, indexes)
      await run('window.anchorsTest.jump("user-100")')
      assert.equal((await state()).focusedMessage, 'user-100')
      const aroundCount = (await state()).requests.filter(method => method === 'thread.messages.around').length
      await run('window.anchorsTest.jump("user-100")')
      assert.equal((await state()).focusedMessage, 'user-100')
      assert.ok((await run('window.anchorsTest.loadedIds()')).includes('user-100'))
      assert.equal((await state()).requests.filter(method => method === 'thread.messages.around').length, aroundCount)
      assert.equal(await run('window.anchorsTest.gap()'), true)
      assert.ok(await run('window.anchorsTest.loaderTop() > window.anchorsTest.targetTop("user-100")'))
      await run('window.anchorsTest.jump("user-300")')
      assert.equal((await state()).focusedMessage, 'user-300')
      const ids = await run('window.anchorsTest.loadedIds()')
      assert.ok(!ids.includes('user-100'))
      assert.ok(ids.includes('user-981'))
      assert.ok(ids.length < 90)
      await run('window.anchorsTest.upInput()')
      assert.deepEqual(await run('window.anchorsTest.earlierCursors()'), [])
      await run('window.anchorsTest.atLoader()')
      assert.deepEqual(await run('window.anchorsTest.earlierCursors()'), [])
      await run('window.anchorsTest.upInput()')
      assert.deepEqual(await run('window.anchorsTest.earlierCursors()'), [981 * 3])
      assert.equal((await state()).markers.length, 1000)
      assert.ok((await run('window.anchorsTest.loadedIds()')).includes('user-961'))
      await run('window.anchorsTest.jump("user-300")')
      await capture('05-complete-index-independent-window')
    })
    await check('preview failure preserves the title and keyboard retry keeps navigation focus', async () => {
      await move({ x: 600, y: 40 })
      await run('window.anchorsTest.railTop()')
      await run('window.anchorsTest.failNextPreview()')
      const failed = await move(await run('window.anchorsTest.firstMarker()'))
      assert.equal(failed.title, await run('window.anchorsTest.longTitle'))
      assert.ok(failed.reply.includes('重试'))
      await run("document.querySelector('.conversation-anchor-preview button').focus()")
      const retried = await key('Enter')
      assert.equal(retried.reply, await run('window.anchorsTest.firstReply'))
      assert.equal(retried.focusedAnchor, 'user-1')
      await key('Escape')
      assert.equal((await state()).title, null)
    })
    assert.deepEqual(errors, [])
    assert.ok((await state()).requests.every(method => ['skills.list', 'skills.deliveryGroups.list', 'camp.pendingInputs.get', 'thread.messages.anchors', 'thread.messages.anchorPreview', 'thread.messages.around'].includes(method)))
    const report = { ok: true, checks }
    writeFileSync(join(evidence, 'verification.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report))
    app.exit(0)
  } catch (error) {
    console.error(error)
    const snapshot = await state().catch(() => null)
    console.error(JSON.stringify({ state: snapshot && { ...snapshot, markerCount: snapshot.markers.length,
      markers: snapshot.markers.filter(marker => marker.current || marker.id === snapshot.focusedAnchor) }, errors, checks }))
    await capture('failure')
    app.exit(1)
  }
})
