const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
// Production CampWorkspace, closed metadata/draft API. No Core, Runtime or daily data is opened.
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux' || process.env.ROVAI_SHOW_FAST_FIXTURE === '1', width: 1280, height: 720, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  await window.loadFile(renderer)
  const run = code => window.webContents.executeJavaScript(code, true)
  const snapshot = async () => { await run('window.fastTest.settle()'); return run('window.fastTest.snapshot()') }
  const click = async selector => {
    const point = await run(`(() => { const node = document.querySelector(${JSON.stringify(selector)}); if (!node) throw new Error('Missing '+${JSON.stringify(selector)}); node.scrollIntoView({block:'nearest'}); const r=node.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)} })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    return snapshot()
  }
  const key = async keyCode => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode })
    if (keyCode === 'Enter') window.webContents.sendInputEvent({ type: 'char', keyCode: '\r' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode })
    return snapshot()
  }
  const capture = async name => writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
  try {
    let state = await snapshot()
    assert.equal(state.panel.height, 0, 'Members start collapsed, as in the production workspace')
    assert.equal(state.checks.length, 3, 'Workspace entry warms uncached metadata before opening either surface')
    assert.equal(state.memberFast['agent-4'], false, 'A failed background check remains hidden')
    state = await click('.camp-detail-entry[data-detail="members"]')
    assert.ok(state.panel.height > 0, 'Native input opens the production member popover')
    assert.deepEqual(state.checks.map(check => check.agentId).sort(), ['agent-1', 'agent-3', 'agent-4', 'agent-4'], 'Only uncached Claude/Codex members are checked, with failures retried on opening')
    assert.ok(state.checks.every(check => check.campId === 'rvcamp_01m0wzxbb8e1ht984tsbjmysfe'))
    assert.equal(state.memberFast['agent-1'], false, 'Pending checks have no placeholder control')
    assert.equal(state.memberFast['agent-4'], true, 'Opening retries a failed background check')
    assert.equal(state.notice, '', 'Automatic checks and failures are silent')
    assert.equal(state.checkingText, false)
    assert.equal(await run("document.querySelector('.camp-fast-toggle').getAttribute('aria-disabled')"), 'false', 'A background check does not block other Fast controls')
    await click('.camp-detail-entry[data-detail="members"]')
    state = await click('.camp-detail-entry[data-detail="members"]')
    assert.equal(state.checks.filter(check => check.agentId === 'agent-1').length, 1, 'Reopening coalesces an in-flight check')
    assert.equal(state.checks.filter(check => check.agentId === 'agent-3').length, 1, 'A known unsupported account is cached')
    assert.equal(state.checks.filter(check => check.agentId === 'agent-4').length, 2, 'A successful retry is cached on subsequent openings')
    assert.equal(state.memberFast['agent-4'], true)
    await run('window.fastTest.releaseCheck()')
    state = await snapshot()
    assert.equal(state.toggles, 14, 'Supported Claude and Codex members appear automatically; other Runtime and unsupported auth stay hidden')
    assert.equal(state.notice, '')
    const checkedCount = state.checks.length
    await click('.camp-detail-entry[data-detail="members"]')
    await click('.camp-detail-entry[data-detail="members"]')
    await click('.camp-detail-entry[data-detail="tasks"]')
    state = await click('.camp-detail-entry[data-detail="members"]')
    assert.equal(state.checks.length, checkedCount, 'Positive and negative results survive reopening and tab changes')
    assert.ok(state.scrollable)
    assert.ok(state.panel.bottom <= state.composer.top, '1280×720 popover must stay above Composer')
    assert.ok(state.sendHit && state.send.bottom <= 720)
    assert.ok(state.button.height >= 28 && Number.parseFloat(state.fontSize) >= 10.5)
    assert.ok(state.pillHeight >= 20 && state.pillHeight <= 22)
    assert.equal(state.pageOverflow, false)
    const dayBackground = state.panelBackground
    await capture('fast-day-1280')
    assert.equal(state.saved.fastOverride, null, 'An untouched Camp preference follows the Runtime default')
    assert.equal(state.pressed, 'mixed')
    await run('window.fastTest.bookmark()')
    state = await click('.camp-members-panel .camp-fast-toggle')
    assert.equal(state.saves.length, 1, 'The first click saves Fast directly')
    assert.equal(state.pressed, 'true')
    assert.equal(state.notice, '', 'Enabling Fast does not show a success reminder')
    assert.ok(state.sameNode && state.focused, 'The toggle keeps its DOM node and focus')
    state = await key('Enter')
    assert.equal(state.pressed, 'false')
    assert.equal(state.notice, '', 'Disabling Fast does not show a success reminder')
    assert.ok(state.sameNode && state.focused)
    state = await key('Enter')
    assert.equal(state.pressed, 'true')
    await run('window.fastTest.failNext()')
    state = await key('Enter')
    assert.equal(state.pressed, 'true', 'Failed save leaves the prior intent visible')
    assert.ok(state.sameNode && state.focused)
    for (const observed of ['fast', 'standard', 'cooldown']) {
      await run(`window.fastTest.legacyObservation('${observed}')`)
      state = await snapshot()
      assert.equal(state.saved.fastOverride, true)
      assert.equal(state.pressed, 'true')
      assert.ok(state.label.includes('后续执行请求 Fast'))
      assert.equal(await run("document.querySelector('.camp-fast-warning') !== null"), false)
    }
    await run('window.fastTest.holdNext()')
    state = await click('.camp-members-panel .camp-fast-toggle')
    assert.equal(state.memberStates[0].pending, 'true')
    assert.ok(state.memberStates.slice(1).filter(member => member.pending !== undefined).every(member => member.pending === 'false' && member.opacity === '1'), 'Saving one member must not dim or block any other member')
    const concurrentSaves = state.saves.length
    state = await click('.camp-inspector-member-row:nth-child(2) .camp-fast-toggle')
    assert.equal(state.saves.length, concurrentSaves + 1, 'A different member can save while the first request is pending')
    assert.equal(state.memberStates[0].pending, 'true', 'The other completion cannot clear this pending request')
    assert.equal(state.memberStates[1].pressed, 'true')
    await run('window.fastTest.release()')
    state = await snapshot()
    assert.equal(state.memberStates[0].pending, 'false')
    assert.equal(state.memberStates[0].pressed, 'false')
    assert.equal(state.memberStates[1].pressed, 'true', 'The delayed response cannot overwrite another member')
    state = await click('.camp-members-panel .camp-fast-toggle')
    assert.equal(state.memberStates[0].pressed, 'true')
    await click('.camp-member-action-button')
    assert.equal((await snapshot()).checkingText, false, 'There are no manual detection or reset menu items')
    state = await key('Escape')
    if (state.panel.height === 0) state = await click('.camp-detail-entry[data-detail="members"]')
    await run("document.documentElement.dataset.theme = 'night'")
    state = await snapshot()
    assert.notEqual(state.panelBackground, dayBackground, 'Night tokens must be painted before capturing')
    await capture('fast-night-1280')
    window.webContents.debugger.attach('1.3')
    for (const [width, height] of [[1040, 700], [1440, 920]]) {
      await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: false })
      state = await snapshot()
      assert.ok(state.panel.bottom <= state.composer.top && state.sendHit, `${width}×${height} keeps Composer reachable`)
      assert.equal(state.pageOverflow, false)
    }
    const beforeRebindChecks = state.checks.length
    await run("window.fastTest.holdCheck('agent-0'); window.fastTest.rebind('claude-code-cli', true, true)")
    state = await snapshot()
    assert.equal(state.checks.length, beforeRebindChecks + 1, 'A new binding is checked automatically')
    assert.equal(state.memberFast['agent-0'], false, 'A stale Camp projection cannot keep the prior binding visible while profiles refresh')
    const previousNotice = state.notice
    await run("window.fastTest.rebind('codex-cli')")
    state = await snapshot()
    assert.equal(state.checks.length, beforeRebindChecks + 1, 'An old check finishes before another is queued for the same member')
    await run('window.fastTest.releaseCheck()')
    state = await snapshot()
    assert.equal(state.checks.length, beforeRebindChecks + 2)
    assert.equal(state.toggles, 13, 'A delayed check cannot restore the previous binding even on another Fast-capable Runtime')
    assert.equal(state.notice, previousNotice, 'Neither a supported nor unsupported automatic result emits a notification')
    await run("window.fastTest.rebind('codex-cli', true)")
    state = await snapshot()
    assert.equal(state.memberFast['agent-0'], true, 'Switching to an eligible official Runtime shows Fast automatically')
    await run("window.fastTest.rebind('codex-cli')")
    state = await snapshot()
    assert.equal(state.memberFast['agent-0'], false, 'A non-official/provider binding with no eligible metadata hides Fast')
    const beforeOtherRuntime = state.checks.length
    await run("window.fastTest.rebind('opencode-cli')")
    state = await snapshot()
    assert.equal(state.checks.length, beforeOtherRuntime, 'Other runtimes never receive Fast checks')
    await run("window.fastTest.rebind('claude-code-cli', true)")
    state = await snapshot()
    assert.equal(state.memberFast['agent-0'], true)
    await run('window.fastTest.holdNext()')
    await click('.camp-members-panel .camp-fast-toggle')
    await run("window.fastTest.rebind('opencode-cli')")
    await snapshot()
    await run('window.fastTest.release()')
    state = await snapshot()
    assert.equal(state.toggles, 13, 'A delayed save cannot show Fast on an unsupported Runtime')
    assert.equal(state.maxChecksPerMember, 1)
    assert.equal(state.checkingText, false)
    await run("window.fastTest.rebind('claude-code-cli', true)")
    await snapshot()
    await click('.camp-detail-entry[data-detail="members"]')
    await run('window.fastTest.showExecution()')
    await snapshot()
    await click('.camp-detail-entry[data-detail="execution"]')
    await click('.run-pulse [data-agent-id="agent-0"]')
    const previousProcess = '[data-agent-run-id="previous-agent-0"] .execution-disclosure'
    assert.equal(await run("document.querySelector('.execution-run-information')"), null, 'Run metadata no longer occupies a separate disclosure')
    assert.equal(await run("document.querySelectorAll('.execution-process-card').length"), 2, 'Completed and running Runs remain separate cards')
    assert.equal(await run(`document.querySelector('${previousProcess}').open`), false, 'Completed process starts collapsed')
    assert.equal(await run("Boolean(document.querySelector('[data-agent-run-id=\"previous-agent-0\"] .execution-process-node circle'))"), true, 'The completed Run retains its circular status glyph')
    await click(`${previousProcess} > summary`)
    await run("window.bookmarkedExecutionDrawer = document.querySelector('.execution-drawer')")
    await run('window.fastTest.refresh()')
    await snapshot()
    assert.equal(await run(`document.querySelector('${previousProcess}').open`), true, 'Projection refresh preserves the execution process disclosure')
    state = await key('Escape')
    assert.equal(state.panel.height, 0, 'Escape from execution details closes the floating panel')
    assert.equal(await run("document.activeElement.matches('.camp-detail-entry[data-detail=\"execution\"]')"), true, 'Focus returns to the floating panel entry')
    await click('.camp-detail-entry[data-detail="execution"]')
    assert.equal(await run("window.bookmarkedExecutionDrawer === document.querySelector('.execution-drawer')"), true, 'Closing the panel does not remount execution details')
    assert.equal(await run(`document.querySelector('${previousProcess}').open`), true, 'Reopening preserves the completed process disclosure')
    await click(`${previousProcess} > summary`)
    await key('Enter')
    assert.equal(await run(`document.querySelector('${previousProcess}').open`), true, 'The focused process summary opens with native keyboard input')
    await key('Enter')
    const executionFast = '.execution-drawer .camp-fast-toggle'
    const stopButton = '.execution-drawer [aria-label="停止当前运行"]'
    const executionState = () => run(`(() => {
      const fast = document.querySelector('${executionFast}'), stop = document.querySelector('${stopButton}')
      const close = document.querySelector('.execution-drawer [aria-label="收起执行详情"]')
      const drawer = document.querySelector('.execution-drawer'), header = drawer.querySelector('.execution-drawer-header')
      const model = header.querySelector('.execution-model-params'), config = header.querySelector('.execution-config-line')
      const f = fast?.getBoundingClientRect(), s = stop?.getBoundingClientRect(), c = close?.getBoundingClientRect()
      const m = model?.getBoundingClientRect(), agent = header.querySelector('.execution-drawer-agent').getBoundingClientRect()
      const fastFace = fast?.querySelector('.camp-fast-pill'), stopFace = stop?.querySelector('.execution-drawer-action-face')
      const closeFace = close?.querySelector('.execution-drawer-action-face')
      const probe = document.createElement('div'); probe.className = 'app-dialog'; probe.style.position = 'fixed'; probe.style.left = '-9999px'
      probe.innerHTML = '<button class="danger-button">删除对话</button>'; document.body.appendChild(probe)
      const expected = getComputedStyle(probe.firstElementChild), actual = stopFace ? getComputedStyle(stopFace) : null
      const result = { pressed: fast?.getAttribute('aria-pressed'), pending: fast?.getAttribute('aria-busy'),
        order: !!s && !!f && config.contains(fast) && f.left-m.right >= 9 && s.left-agent.right >= 11 &&
          (drawer.dataset.placement === 'inspector' ? !close : !!c && c.left-s.right >= 7),
        equalFaces: Math.abs(fastFace?.getBoundingClientRect().height-stopFace?.getBoundingClientRect().height) < 1 &&
          (!closeFace || Math.abs(closeFace.getBoundingClientRect().height-stopFace?.getBoundingClientRect().height) < 1),
        model: model.textContent,
        openSurface: getComputedStyle(header).backgroundColor === getComputedStyle(drawer).backgroundColor,
        stopHit: !!s && s.height >= 28 && document.elementFromPoint(s.x+s.width/2,s.y+s.height/2)?.closest('[aria-label="停止当前运行"]') === stop,
        fastHit: !!f && f.height >= 28 && document.elementFromPoint(f.x+f.width/2,f.y+f.height/2)?.closest('.camp-fast-toggle') === fast,
        deleteColors: actual?.color === expected.color && actual?.backgroundColor === expected.backgroundColor,
        actions: document.querySelector('.execution-drawer-actions')?.textContent }
      probe.remove(); return result
    })()`)
    assert.equal((await executionState()).pressed, 'mixed')
    await click(executionFast)
    assert.equal((await executionState()).pressed, 'true')
    await click('.camp-detail-entry[data-detail="members"]')
    state = await snapshot()
    assert.equal(state.memberStates[0].pressed, 'true', 'Execution Fast saves into the same member preference')
    await click('.camp-members-panel .camp-fast-toggle')
    await click('.camp-detail-entry[data-detail="execution"]')
    assert.equal((await executionState()).pressed, 'false', 'Member Fast also updates execution details')
    await run('window.fastTest.refresh()')
    await snapshot()
    assert.equal((await executionState()).pressed, 'false', 'An unrelated cloned projection does not erase a saved preference')
    for (const placement of ['inspector', 'bottom']) {
      if (placement === 'bottom') await click('.run-pulse-inspector .execution-placement-button')
      for (const theme of ['day', 'night']) {
        await run(`document.documentElement.dataset.theme = '${theme}'`)
        for (const [width, height] of [[1040,700], [1440,920]]) {
          await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', {width,height,deviceScaleFactor:1,mobile:false})
          await snapshot()
          await run("Promise.all(document.getAnimations().filter(animation => animation instanceof CSSTransition).map(animation => animation.finished.catch(() => {})))")
          const result = await executionState()
          assert.ok(result.order && result.equalFaces && result.stopHit && result.fastHit && result.deleteColors && result.openSurface, JSON.stringify({placement, theme, width, result}))
          assert.equal(result.model, 'claude-sonnet-4-6 · 思考强度 高')
          await capture(`execution-fast-${placement}-${theme}-${width}`)
        }
      }
    }
    await click('.camp-detail-entry[data-detail="members"]')
    await run('window.fastTest.holdNext()')
    await click('.camp-members-panel .camp-fast-toggle')
    assert.equal((await executionState()).pending, 'true', 'Both surfaces share this member pending state')
    const pendingSaves = (await snapshot()).saves.length
    await click(executionFast)
    assert.equal((await snapshot()).saves.length, pendingSaves, 'The second surface cannot submit the same member twice')
    await click('.run-pulse [data-agent-id="agent-1"]')
    assert.equal((await executionState()).pending, 'false', 'Switching execution member never inherits another pending state')
    await run('window.fastTest.release()')
    await snapshot()
    await click('.camp-detail-entry[data-detail="members"]')
    await click('.run-pulse [data-agent-id="agent-2"]')
    assert.equal(await run(`Boolean(document.querySelector('${executionFast}'))`), false, 'An unsupported execution Runtime has no Fast control')
    await click('.run-pulse [data-agent-id="agent-0"]')
    await click(stopButton)
    assert.ok((await executionState()).actions.includes('正在提交停止请求'))
    await run('window.fastTest.releaseStop()')
    await snapshot()
    assert.ok((await executionState()).actions.includes('已停止'))
    assert.equal((await executionState()).pressed, 'true', 'Stopping the run keeps the next-run preference')
    await click('.execution-placement-button')
    await click('.conversation-controls .composer-primary-action')
    await snapshot()
    const followState = () => run(`(() => {
      const body = document.querySelector('.execution-drawer-body')
      const stage = document.querySelector('.execution-process-stage.is-focused')
      return { id: stage?.dataset.agentRunId, expanded: !!stage?.querySelector('.run-live'),
        visible: !!body?.getBoundingClientRect().height,
        following: body?.dataset.followingLatest, gap: body.scrollHeight - body.scrollTop - body.clientHeight }
    })()`)
    const follow = await followState()
    assert.equal(follow.id, 'submitted-run-1', 'Sending after cancellation selects the new Run')
    assert.equal(follow.expanded, true, 'Sending after cancellation expands the new execution process')
    assert.equal(follow.following, 'true', 'Sending after cancellation restores output following')
    assert.ok(follow.gap <= 1, `Sending after cancellation scrolls to the latest output: ${JSON.stringify(follow)}`)
    for (const placement of ['inspector', 'bottom']) {
      if (placement === 'bottom') await click('.execution-placement-button')
      const previous = await followState()
      await run('window.fastTest.queueNextSend()')
      await click('.conversation-controls .composer-primary-action')
      assert.equal((await followState()).id, previous.id, 'Admission alone does not select a guessed Run')
      await click(stopButton)
      await run('window.fastTest.releaseStop()')
      await snapshot()
      if (placement === 'inspector') await click('.camp-detail-entry[data-detail="execution"]')
      await run("document.querySelector('.conversation-controls .structured-mention-editor').focus({preventScroll:true})")
      await run('window.fastTest.publishQueued(true)')
      await snapshot()
      assert.equal((await followState()).id, previous.id, 'A publication receipt waits for its exact Run projection')
      await run('window.fastTest.projectPublishedRun()')
      await snapshot()
      const published = await followState()
      assert.equal(published.id, placement === 'inspector' ? 'submitted-run-2' : 'submitted-run-3')
      assert.ok(published.visible && published.expanded, 'Queued publication after Stop opens the new execution process')
      assert.equal(published.following, 'true')
      assert.ok(published.gap <= 1, `Queued publication follows the latest output: ${JSON.stringify(published)}`)
      assert.equal(await run("document.activeElement.matches('.structured-mention-editor')"), true, 'Publication preserves Composer focus')
    }
    await click(stopButton)
    await run('window.fastTest.releaseStop()')
    await snapshot()
    await run('window.fastTest.queueNextSend(true)')
    await click('.conversation-controls .composer-primary-action')
    assert.equal((await followState()).id, 'submitted-run-4', 'Durable outcomes also resolve publication before the send receipt')
    console.log(JSON.stringify({ ok: true, requests: state.requests.length, cases: ['1280×720', '1040×700', '1440×920', 'direct toggle', 'native keyboard/focus', 'save failure', 'observations ignored', 'automatic detection', 'silent failure/retry', 'positive/negative cache', 'in-flight coalescing', 'runtime/auth rebind', 'inherited default', 'late check', 'late save', 'member-scoped pending', 'concurrent member saves', 'execution/member sync', 'stop/delete colors', 'execution placement/theme matrix', 'shared duplicate guard', 'projection refresh'] }))
    window.destroy(); app.quit()
  } catch (error) {
    console.error(await snapshot())
    await capture('failure')
    throw error
  }
}).catch(error => { console.error(error); app.exit(1) })
