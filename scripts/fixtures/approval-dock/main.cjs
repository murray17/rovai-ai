const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
// Only the production approval component and styles are loaded. No Core, Runtime, IPC or daily data.
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1440, height: 920, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  await window.loadFile(renderer)
  const run = code => window.webContents.executeJavaScript(code, true)
  const snapshot = async () => { await run('window.approvalTest.settle()'); return run('window.approvalTest.snapshot()') }
  const click = async selector => {
    const point = await run(`(() => { const node=document.querySelector(${JSON.stringify(selector)}); if(!node) throw new Error('Missing '+${JSON.stringify(selector)}); node.scrollIntoView({block:'nearest'}); const r=node.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)} })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    return snapshot()
  }
  const enter = async () => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Enter' })
    window.webContents.sendInputEvent({ type: 'char', keyCode: '\r' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Enter' })
    return snapshot()
  }
  const capture = async name => writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
  try {
    let state = await snapshot()
    assert.equal(state.decisionFocused, false, 'Initial render must not select a decision')
    assert.deepEqual(state.labels, ['Runtime Allow once', 'Adapter custom choice', 'Deny', 'Allow for this session'])
    assert.equal(state.consequenceVisible, false)
    assert.equal(state.dock.width, state.console.width)
    assert.equal(state.dock.x, state.console.x)
    assert.ok(state.codeScrollable, 'Long command remains complete and scrollable')
    assert.equal(state.codeText, state.expectedCode)
    assert.equal(state.codeFocusable, true)
    assert.equal(state.dockShadow, 'none')
    assert.equal(state.codeBackground, 'rgb(243, 244, 243)', 'Day approval matches the command result surface')
    assert.equal(state.reasonToggle, false, 'The initial wide reason fits in two lines')
    await capture('approval-day-wide')

    state = await click('#draft')
    await run('window.approvalTest.refresh()')
    state = await snapshot()
    assert.equal(state.active, 'draft', 'A data refresh must not steal Composer focus')
    state = await click('#locate')
    assert.ok(state.summaryFocused)
    assert.equal(state.presented.length, 1, 'Notification acknowledgement follows summary focus')
    await enter()
    assert.equal((await snapshot()).requests.length, 0, 'Enter on a summary cannot authorize')

    state = await click('[aria-label="下一项审批"]')
    assert.equal(state.id, 'approval-2')
    assert.equal(state.active, '下一项审批')
    state = await enter()
    assert.equal(state.id, 'approval-3')
    assert.equal(state.active, '下一项审批')
    assert.equal(state.nextDisabled, 'true')
    state = await enter()
    assert.equal(state.id, 'approval-3', 'The focused queue boundary is a no-op')
    assert.equal(state.requests.length, 0)
    assert.equal(state.reason, null, 'Only normalized exact duplicate reasons are hidden')
    await click('[aria-label="上一项审批"]')
    await click('[aria-label="上一项审批"]')

    await run("window.approvalTest.locate('approval-2')")
    state = await snapshot()
    assert.equal(state.id, 'approval-2')
    assert.ok(state.summaryFocused)
    state = await click('[aria-label="上一项审批"]')
    assert.equal(state.id, 'approval-1')
    assert.equal(state.active, '上一项审批')
    await click('#draft')
    await run('window.approvalTest.refresh()')
    state = await snapshot()
    assert.equal(state.id, 'approval-1', 'A presented focus request cannot replay on a refresh')
    assert.equal(state.active, 'draft')
    assert.equal(state.presented.length, 2, 'Each focus request is presented exactly once')

    // Change only CSS geometry; no React render/fixture data change can hide a missing observer.
    await run('window.approvalTest.setWidth(420)')
    state = await snapshot()
    assert.equal(state.reasonToggle, true, 'A narrowed conversation must expose the full reason')
    assert.ok(state.reasonScrollHeight > state.reasonHeight)
    assert.equal(state.dock.width, state.console.width)
    state = await click('.approval-reason-toggle')
    assert.equal(state.expanded, 'true')
    assert.equal(state.reason, state.expectedReason)
    assert.ok(state.reasonScrollHeight <= state.reasonHeight + 1)
    state = await click('[aria-label="下一项审批"]')
    assert.equal(state.expanded, 'false', 'Same Runtime/action kind does not share another approval expansion')
    state = await click('[aria-label="上一项审批"]')
    assert.equal(state.expanded, 'true', 'Returning restores the same approval expansion')
    await run('window.approvalTest.setWidth(1200)')
    state = await snapshot()
    assert.equal(state.expanded, 'true', 'Width changes preserve the current approval expansion')
    await click('.approval-reason-toggle')
    await run('window.approvalTest.setWidth(420)')
    state = await snapshot()
    assert.equal(state.expanded, 'false')
    await capture('approval-day-narrow')

    const day = state.background
    await run("document.documentElement.dataset.theme='night'")
    state = await snapshot()
    assert.notEqual(state.background, day)
    await capture('approval-night-narrow')
    window.webContents.debugger.attach('1.3')
    await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width: 1040, height: 700, deviceScaleFactor: 1, mobile: false })
    state = await snapshot()
    assert.equal(state.pageOverflow, false)
    assert.ok(state.dock.height <= 315 && state.dock.bottom <= 700)
    assert.ok(state.code.height <= 210)
    await capture('approval-night-minimum')

    state = await click('.runtime-option')
    assert.deepEqual(state.requests, [{ approvalId: 'approval-1', optionId: 'native-once', version: 1 }])
    assert.ok(state.disabled)
    await run('window.approvalTest.complete()')
    state = await snapshot()
    assert.equal(state.id, 'approval-2')
    assert.ok(state.summaryFocused && !state.decisionFocused)
    await enter()
    assert.equal((await snapshot()).requests.length, 1)
    await click('[aria-label="收起审批详情"]')
    state = await click('#locate')
    assert.ok(state.summaryFocused)
    assert.equal(state.reason, state.expectedReason)
    await run("document.querySelector('.approval-dock-scroll > pre').focus()")
    state = await enter()
    assert.equal(state.requests.length, 1, 'Enter while reading JSON cannot submit a decision')

    // Exercise the same production Dock with Web-only mobile presentation enabled.
    await run('window.approvalTest.reset(); window.approvalTest.setMobile(true); window.approvalTest.setWidth(1200)')
    for (const theme of ['day', 'night']) {
      await run(`document.documentElement.dataset.theme=${JSON.stringify(theme)}`)
      for (const [width, height] of [[375, 812], [390, 844], [430, 932], [844, 390], [390, 500]]) {
        await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: true })
        state = await snapshot()
        assert.equal(state.pageOverflow, false)
        assert.equal(state.codeText, state.expectedCode)
        assert.equal(state.codeBackground, theme === 'day' ? 'rgb(243, 244, 243)' : 'rgb(55, 63, 67)')
        assert.ok(state.touchTargets.every(target => target.width >= 44 && target.height >= 44), JSON.stringify(state.touchTargets))
        assert.ok(state.dock.height <= height * .56 + 1)
        state = await click('#locate')
        assert.ok(state.summaryFocused)
        assert.ok(state.dock.top >= state.controls.top - 1, 'Approval heading is reachable at reduced height')
        await capture(`approval-mobile-${theme}-${width}x${height}`)
      }
    }
    state = await click('.runtime-option')
    assert.deepEqual(state.requests, [{ approvalId: 'approval-1', optionId: 'native-once', version: 1 }])
    assert.ok(state.disabled, 'Scrolling to a phone decision retains the original native response')
    await run('window.approvalTest.complete()')
    state = await snapshot()
    assert.ok(state.summaryFocused && !state.decisionFocused)
    await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width: 375, height: 812, deviceScaleFactor: 1, mobile: true })
    await run('window.approvalTest.manyOptions()')
    state = await snapshot()
    assert.equal(state.labels.length, 12)
    const wheelPoint = await run("(() => { const r=document.querySelector('.approval-dock-scroll').getBoundingClientRect(); return { x:Math.round(r.x+r.width/2), y:Math.round(r.y+r.height/2) } })()")
    const scrollBefore = await run(`(() => { const node=document.querySelector('.approval-dock-scroll'); return { top:node.scrollTop, height:node.clientHeight, content:node.scrollHeight, bounds:node.getBoundingClientRect().toJSON(), hit:document.elementFromPoint(${wheelPoint.x},${wheelPoint.y})?.className } })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...wheelPoint })
    for (let wheel = 0; wheel < 2; wheel++) {
      window.webContents.sendInputEvent({ type: 'mouseWheel', ...wheelPoint, deltaY: -10000, deltaX: 0, canScroll: true })
      await run('new Promise(resolve => setTimeout(resolve, 250))')
    }
    const scrollAfter = await run("document.querySelector('.approval-dock-scroll').scrollTop")
    assert.ok(await run("(() => { const button=document.querySelector('.runtime-option:last-child'); const r=button.getBoundingClientRect(); return document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)===button })()"), `The last native option remains reachable by user scrolling: ${JSON.stringify({ wheelPoint, scrollBefore, scrollAfter })}`)
    state = await click('.runtime-option:last-child')
    assert.deepEqual(state.requests[1], { approvalId: 'approval-2', optionId: 'extended-11', version: 2 })

    // Change language on an already mounted Dock. Only Core-owned copy is localized.
    for (const source of ['core', 'claude', 'claude-remember', 'native']) {
      await run(`window.approvalTest.setOptionsSource(${JSON.stringify(source)})`)
      await run("window.approvalTest.setLanguage('zh-CN')")
      state = await snapshot()
      const nativeClaude = source.startsWith('claude')
      const rememberLabels = source === 'claude-remember' ? ['Yes, and don’t ask again for: rovai send *'] : []
      const chineseLabels = nativeClaude ? ['No', 'Yes', ...rememberLabels] : ['拒绝', '允许一次']
      assert.deepEqual(state.labels, chineseLabels)
      const identities = { optionIds: state.optionIds, nativeResponseDigests: state.nativeResponseDigests }
      await run("window.approvalTest.setLanguage('en')")
      state = await snapshot()
      const labels = source === 'core' ? ['Reject', 'Allow once'] : chineseLabels
      assert.deepEqual(state.labels, labels, 'Runtime choices keep their native labels in both languages')
      assert.deepEqual({ optionIds: state.optionIds, nativeResponseDigests: state.nativeResponseDigests }, identities)
      assert.deepEqual(state.titles, labels)
      assert.deepEqual(state.accessibleLabels, labels)
      assert.equal(state.summary, '允许一次', 'Request summaries remain verbatim')
      assert.equal(state.reason, '拒绝', 'Request reasons remain verbatim')
      assert.equal(state.codeText, state.expectedCode)
      assert.equal(state.consequenceVisible, false)
      assert.equal(state.configurationVisible, false, 'Approval choices do not expose configuration destinations or filenames')
      assert.equal(state.pageOverflow, false)
      await capture(`approval-language-${source}`)
      await run("window.approvalTest.setLanguage('zh-CN')")
      assert.deepEqual((await snapshot()).labels, chineseLabels)
      await run("window.approvalTest.setLanguage('en')")
      const optionId = source === 'core' ? 'core.deny' : source === 'claude-remember' ? 'claude.allow_remember.rule-digest' : 'claude.allow_once'
      state = await click(`[data-option-id="${optionId}"]`)
      assert.deepEqual(state.requests, [{ approvalId: 'approval-1', optionId, version: 1 }])
      assert.ok(state.disabled)
    }
    await run("window.approvalTest.setOptionsSource('claude-remember'); document.documentElement.dataset.theme='day'")
    for (const [width, height, mobile, rows] of [[1440, 920, false, 1], [375, 812, true, 2], [430, 932, true, 1]]) {
      await run(`window.approvalTest.setMobile(${mobile}); window.approvalTest.setWidth(1200)`)
      await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile })
      state = await snapshot()
      assert.equal(new Set(state.optionBounds.map(bounds => Math.round(bounds.y))).size, rows, 'Native choices share one row when they fit and wrap to two when needed')
      assert.deepEqual(state.labels, ['No', 'Yes', 'Yes, and don’t ask again for: rovai send *'])
      assert.equal(state.configurationVisible, false)
      assert.equal(state.pageOverflow, false)
      if (mobile) assert.ok(state.touchTargets.every(target => target.width >= 44 && target.height >= 44))
      await capture(`approval-claude-inline-${width}`)
    }
    await run('window.approvalTest.longRememberRule()')
    for (const [width, height, mobile] of [[1040, 700, false], [375, 812, true], [430, 932, true]]) {
      await run(`window.approvalTest.setMobile(${mobile})`)
      await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile })
      state = await snapshot()
      assert.equal(state.pageOverflow, false, 'Complete native rule labels wrap without page overflow')
      assert.ok(state.labels[2].endsWith('/a-long-project-directory'.repeat(12) + '/*'))
      assert.equal(state.accessibleLabels[2], state.labels[2])
      assert.equal(state.configurationVisible, false)
      assert.equal(new Set(state.optionBounds.map(bounds => Math.round(bounds.y))).size, 2)
      if (mobile) assert.ok(state.touchTargets.every(target => target.width >= 44 && target.height >= 44))
      await capture(`approval-remember-long-${width}`)
    }
    console.log(JSON.stringify({ ok: true, cases: ['native labels/order/optionId', 'queue keyboard boundaries', 'summary focus', 'refresh focus', 'exact reason dedup', 'resize without rerender', 'approval identity', 'day/night', '1040×700', '420px conversation', 'complete command', '375/390/430px mobile', 'landscape/reduced viewport', '44px targets', 'scrolling long option lists', 'live language changes', 'Core-owned approval labels', 'native Claude English in both languages', 'native text preservation', 'decision identity', 'configuration details hidden', 'one row when choices fit', 'two rows when needed', 'long remember rule accessibility/wrapping'] }))
    window.destroy(); app.quit()
  } catch (error) {
    console.error(await snapshot())
    await capture('failure')
    throw error
  }
}).catch(error => { console.error(error); app.exit(1) })
