const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
// Only the production approval component and styles are loaded. No Core, Runtime, IPC or daily data.
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: process.platform === 'linux', width: 1440, height: 920, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  await window.loadFile(renderer)
  const run = code => window.webContents.executeJavaScript(code, true)
  const snapshot = async () => { await run('window.approvalTest.settle()'); return run('window.approvalTest.snapshot()') }
  const click = async selector => {
    const point = await run(`(() => { const node=document.querySelector(${JSON.stringify(selector)}); if(!node) throw new Error('Missing '+${JSON.stringify(selector)}); node.scrollIntoView({block:'nearest'}); const r=node.getBoundingClientRect(); return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)} })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    return snapshot()
  }
  const enter = async () => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Enter' })
    window.webContents.sendInputEvent({ type: 'char', keyCode: '\r' })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Enter' })
    return snapshot()
  }
  const capture = async name => writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
  try {
    let state = await snapshot()
    assert.equal(state.decisionFocused, false, 'Initial render must not select a decision')
    assert.deepEqual(state.labels, ['Runtime Allow once', 'Adapter custom choice', 'Deny', 'Allow for this session'])
    assert.equal(state.consequenceVisible, false)
    assert.equal(state.dock.width, state.console.width)
    assert.equal(state.dock.x, state.console.x)
    assert.ok(state.codeScrollable, 'Long command remains complete and scrollable')
    assert.equal(state.reasonToggle, false, 'The initial wide reason fits in two lines')
    await capture('approval-day-wide')

    state = await click('#draft')
    await run('window.approvalTest.refresh()')
    state = await snapshot()
    assert.equal(state.active, 'draft', 'A data refresh must not steal Composer focus')
    state = await click('#locate')
    assert.ok(state.summaryFocused)
    assert.equal(state.presented.length, 1, 'Notification acknowledgement follows summary focus')
    await enter()
    assert.equal((await snapshot()).requests.length, 0, 'Enter on a summary cannot authorize')

    state = await click('[aria-label="下一项审批"]')
    assert.equal(state.id, 'approval-2')
    assert.equal(state.active, '下一项审批')
    state = await enter()
    assert.equal(state.id, 'approval-3')
    assert.equal(state.active, '下一项审批')
    assert.equal(state.nextDisabled, 'true')
    state = await enter()
    assert.equal(state.id, 'approval-3', 'The focused queue boundary is a no-op')
    assert.equal(state.requests.length, 0)
    assert.equal(state.reason, null, 'Only normalized exact duplicate reasons are hidden')
    await click('[aria-label="上一项审批"]')
    await click('[aria-label="上一项审批"]')

    await run("window.approvalTest.locate('approval-2')")
    state = await snapshot()
    assert.equal(state.id, 'approval-2')
    assert.ok(state.summaryFocused)
    state = await click('[aria-label="上一项审批"]')
    assert.equal(state.id, 'approval-1')
    assert.equal(state.active, '上一项审批')
    await click('#draft')
    await run('window.approvalTest.refresh()')
    state = await snapshot()
    assert.equal(state.id, 'approval-1', 'A presented focus request cannot replay on a refresh')
    assert.equal(state.active, 'draft')
    assert.equal(state.presented.length, 2, 'Each focus request is presented exactly once')

    // Change only CSS geometry; no React render/fixture data change can hide a missing observer.
    await run('window.approvalTest.setWidth(420)')
    state = await snapshot()
    assert.equal(state.reasonToggle, true, 'A narrowed conversation must expose the full reason')
    assert.ok(state.reasonScrollHeight > state.reasonHeight)
    assert.equal(state.dock.width, state.console.width)
    state = await click('.approval-reason-toggle')
    assert.equal(state.expanded, 'true')
    assert.equal(state.reason, state.expectedReason)
    assert.ok(state.reasonScrollHeight <= state.reasonHeight + 1)
    state = await click('[aria-label="下一项审批"]')
    assert.equal(state.expanded, 'false', 'Same Runtime/action kind does not share another approval expansion')
    state = await click('[aria-label="上一项审批"]')
    assert.equal(state.expanded, 'true', 'Returning restores the same approval expansion')
    await run('window.approvalTest.setWidth(1200)')
    state = await snapshot()
    assert.equal(state.expanded, 'true', 'Width changes preserve the current approval expansion')
    await click('.approval-reason-toggle')
    await run('window.approvalTest.setWidth(420)')
    state = await snapshot()
    assert.equal(state.expanded, 'false')
    await capture('approval-day-narrow')

    const day = state.background
    await run("document.documentElement.dataset.theme='night'")
    state = await snapshot()
    assert.notEqual(state.background, day)
    await capture('approval-night-narrow')
    window.webContents.debugger.attach('1.3')
    await window.webContents.debugger.sendCommand('Emulation.setDeviceMetricsOverride', { width: 1040, height: 700, deviceScaleFactor: 1, mobile: false })
    state = await snapshot()
    assert.equal(state.pageOverflow, false)
    assert.ok(state.dock.height <= 315 && state.dock.bottom <= 700)
    assert.ok(state.code.height <= 210)
    await capture('approval-night-minimum')

    state = await click('.runtime-option')
    assert.deepEqual(state.requests, [{ approvalId: 'approval-1', optionId: 'native-once', version: 1 }])
    assert.ok(state.disabled)
    await run('window.approvalTest.complete()')
    state = await snapshot()
    assert.equal(state.id, 'approval-2')
    assert.ok(state.summaryFocused && !state.decisionFocused)
    await enter()
    assert.equal((await snapshot()).requests.length, 1)
    await click('[aria-label="收起审批详情"]')
    state = await click('#locate')
    assert.ok(state.summaryFocused)
    assert.equal(state.reason, state.expectedReason)
    console.log(JSON.stringify({ ok: true, cases: ['native labels/order/optionId', 'queue keyboard boundaries', 'summary focus', 'refresh focus', 'exact reason dedup', 'resize without rerender', 'approval identity', 'day/night', '1040×700', '420px conversation', 'complete command'] }))
    window.destroy(); app.quit()
  } catch (error) {
    console.error(await snapshot())
    await capture('failure')
    throw error
  }
}).catch(error => { console.error(error); app.exit(1) })
