const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
mkdirSync(join(userData, 'managed-skill-library'), { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
const active = '.member-editor-page:not([hidden]) '
let window
app.whenReady().then(async () => {
  window = new BrowserWindow({ show: process.platform === 'linux', width: 1440, height: 920, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  const errors = [], checks = []
  window.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message) })
  const run = expression => window.webContents.executeJavaScript(expression, true)
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  const wait = async expression => {
    for (let attempt = 0; attempt < 120; attempt++) { if (await run('Boolean(' + expression + ')')) return; await pause(25) }
    throw Error('Timed out: ' + expression + '\n' + await run('document.body.innerText.slice(-2500)'))
  }
  const click = async selector => {
    await run('document.querySelector(' + JSON.stringify(selector) + ')?.scrollIntoView({block:"nearest",behavior:"instant"})')
    await pause(60)
    const point = await run('(()=>{const e=document.querySelector(' + JSON.stringify(selector) + ');if(!e)throw Error("Missing click target");const r=e.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()')
    const zoom = window.webContents.getZoomFactor()
    point.x = Math.round(point.x * zoom)
    point.y = Math.round(point.y * zoom)
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    await pause(50)
  }
  const key = async keyCode => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode })
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode })
    await pause(60)
  }
  const check = async (name, expression) => { assert.equal(await run(expression), true, name); checks.push(name) }
  const reset = async (scenario = 'normal') => {
    await run('window.applyFixture.reset(' + JSON.stringify(scenario) + ')')
    await wait('document.querySelector(' + JSON.stringify(active + '[data-apply-entry]') + ')')
    await pause(60)
  }
  const open = async () => { await click(active + '[data-apply-entry]'); await wait('document.querySelector(".runtime-apply-dialog")'); await pause(200) }
  const done = async () => wait('document.querySelector("[data-apply-complete]")')
  const capture = async name => {
    await pause(220)
    const geometry = await run('(()=>{const d=document.querySelector(".runtime-apply-dialog"),f=d?.querySelector(".app-dialog-footer");return {overflow:document.documentElement.scrollWidth>innerWidth,dialog:d?.getBoundingClientRect().toJSON(),footer:f?.getBoundingClientRect().toJSON(),width:innerWidth,height:innerHeight,broken:[...document.images].some(i=>i.complete&&!i.naturalWidth)}})()')
    assert.equal(geometry.overflow, false, name)
    assert.equal(geometry.broken, false, name)
    if (geometry.dialog) {
      assert.ok(geometry.dialog.left >= -1 && geometry.dialog.right <= geometry.width + 1, name)
      assert.ok(geometry.dialog.top >= -1 && geometry.dialog.bottom <= geometry.height + 1, name)
      assert.ok(geometry.footer.top >= 0 && geometry.footer.bottom <= geometry.height + 1, name)
    }
    writeFileSync(join(dirname(userData), name + '.png'), (await window.webContents.capturePage()).toPNG())
    checks.push(name)
  }
  await window.loadFile(renderer)
  await wait('window.applyFixture && document.querySelector("[data-apply-entry]")')
  await capture('desktop-zh-entry')
  await open()
  await check('only unconfigured targets preselected; source excluded', 'document.querySelectorAll(".apply-target").length===3 && document.querySelectorAll(".apply-target input:checked").length===2')
  for (let i = 0; i < 12; i++) { await key('Tab'); await check('keyboard stays in dialog', '!!document.activeElement.closest(".runtime-apply-dialog")') }
  await click('[data-select-all]')
  await click('.apply-permissions summary')
  await check('overwrite and permissions disclosed', '!!document.querySelector(".apply-replace-note") && document.querySelector(".apply-permissions").open')
  await capture('desktop-zh-overwrite')
  await run('window.applyFixture.hold(1)')
  await click('[data-apply-submit]')
  await wait('document.querySelector(".apply-result[data-status=applying]")')
  await key('Escape')
  await check('in-flight saves block close and navigation', 'window.applyFixture.leave().then(ok=>!ok && !!document.querySelector(".runtime-apply-dialog"))')
  await run('window.applyFixture.release()')
  await done()
  await check('each selected target saved once using its reviewed version', 'window.applyFixture.calls.length===3 && window.applyFixture.calls.every(c=>c.command.expectedVersion===1) && window.applyFixture.profiles().every(m=>JSON.stringify(m.runtimeConfiguration)===JSON.stringify(window.applyFixture.profiles()[0].runtimeConfiguration))')
  await capture('desktop-zh-success')

  await reset()
  await click(active + '.runtime-model-picker-trigger')
  await click('.runtime-picker-default [role=option]')
  await check('source draft cannot be applied', 'document.querySelector(' + JSON.stringify(active + '[data-apply-entry]') + ').disabled')
  await run('window.applyFixture.language("en")')
  await check('language preserves source draft', 'document.querySelector(' + JSON.stringify(active + '.runtime-model-picker-trigger') + ').textContent.includes("Default") && window.applyFixture.profiles()[0].runtimeConfiguration.model.mode==="explicit"')
  await click(active + '.member-runtime-form .member-editor-save')
  await wait('!document.querySelector(' + JSON.stringify(active + '[data-apply-entry]') + ').disabled')
  await open()
  await click('[data-select-all]')
  await run('window.applyFixture.language("zh-CN")')
  await check('language preserves target selection', 'document.querySelectorAll(".apply-target input:checked").length===3')
  await key('Escape')

  await reset()
  await run('window.applyFixture.select(2)')
  await pause(80)
  await click(active + '.runtime-model-picker-trigger')
  await click('.runtime-picker-scroll [role=option]')
  await run('window.applyFixture.select(0)')
  await pause(80)
  await open()
  await check('target Runtime draft protected', '[...document.querySelectorAll(".apply-target")].some(e=>e.textContent.includes("有未保存更改")&&e.querySelector("input").disabled)')
  await key('Escape')

  await reset()
  await run('window.applyFixture.select(1)')
  await pause(80)
  await click(active + '.member-identity-form input')
  await run('document.activeElement.select()')
  await window.webContents.insertText('Draft identity preserved')
  await run('window.applyFixture.select(0)')
  await pause(80)
  await open()
  await click('[data-apply-submit]')
  await done()
  await click('[data-apply-complete]')
  await run('window.applyFixture.select(1)')
  await pause(80)
  await check('independent identity draft survives Runtime application', 'document.querySelector(' + JSON.stringify(active + '.member-identity-form input') + ').value==="Draft identity preserved" && window.applyFixture.profiles()[1].displayName!=="Draft identity preserved"')

  await reset()
  await run('window.applyFixture.fail(1,"reject")')
  await open(); await click('[data-apply-submit]'); await done()
  await check('partial success is retained', 'document.querySelectorAll(".apply-result[data-status=applied]").length===1 && document.querySelectorAll(".apply-result[data-status=failed]").length===1')
  await click('[data-apply-complete]'); await done()
  await check('retry excludes successful targets', 'window.applyFixture.calls.length===3 && document.querySelectorAll(".apply-result[data-status=applied]").length===2')

  for (const mode of ['unknown-committed', 'unknown-uncommitted']) {
    await reset(); await run('window.applyFixture.fail(1,' + JSON.stringify(mode) + ')')
    await open(); await click('[data-apply-submit]'); await done()
    await check('lost response needs read-back: ' + mode, 'document.querySelector("[data-apply-complete]").textContent==="核对结果" && window.applyFixture.calls.length===2')
    await run('window.applyFixture.readFailure(true)')
    await click('[data-apply-complete]')
    await wait('document.querySelector(".runtime-apply-dialog .inline-error")')
    await check('failed read cannot replay unknown writes', 'window.applyFixture.calls.length===2 && !!document.querySelector(".apply-result[data-status=unknown]")')
    await run('window.applyFixture.readFailure(false)')
    await click('[data-apply-complete]')
    await wait('!document.querySelector(".apply-result[data-status=unknown]")')
    if (mode === 'unknown-committed') await check('read-back reports matching state without claiming receipt', '!!document.querySelector(".apply-result[data-status=matched]") && window.applyFixture.calls.length===2')
    else { await click('[data-apply-complete]'); await done(); await check('explicit retry retains original version', 'window.applyFixture.calls.length===3 && window.applyFixture.calls[2].command.expectedVersion===1') }
  }

  await reset(); await open()
  await run('window.applyFixture.change(1,window.applyFixture.profiles()[2].runtimeConfiguration,false)')
  await click('[data-apply-submit]'); await done()
  await check('concurrent write is not overwritten', '!!document.querySelector(".apply-result[data-status=conflict]") && window.applyFixture.profiles()[1].runtimeConfiguration.adapterKind==="claude-code-cli"')
  await capture('desktop-conflict')
  await click('[data-apply-complete]')
  await wait('document.querySelector("[data-apply-submit]")')
  await check('conflict rereads and reviews changed configuration', 'document.querySelectorAll(".apply-target input:checked").length===1 && !!document.querySelector(".apply-replace-note")')
  await click('[data-apply-submit]'); await done()
  await check('recovery uses explicitly reviewed newer version', 'window.applyFixture.calls[2].command.expectedVersion===2')

  await reset(); await run('window.applyFixture.reloadFailure(true)'); await open(); await click('[data-apply-submit]'); await done()
  await check('reload failure does not erase confirmed writes', 'document.querySelectorAll(".apply-result[data-status=applied]").length===2 && !!document.querySelector(".runtime-apply-dialog .inline-error")')
  await run('window.applyFixture.reloadFailure(false)'); await click('.runtime-apply-dialog .inline-error button')
  await wait('!document.querySelector(".runtime-apply-dialog .inline-error")')
  await check('refresh retries only reading', 'window.applyFixture.calls.length===2')

  window.webContents.debugger.attach('1.3')
  for (const [width, height, language, theme, touch] of [[1440,920,'en','night',false],[1040,700,'zh-CN','day',false],[2560,1440,'en','day',false],[375,812,'en','night',true],[390,844,'zh-CN','day',true],[430,932,'en','day',true],[844,390,'en','night',true]]) {
    await reset(); await run('window.applyFixture.language(' + JSON.stringify(language) + ')')
    await run('document.documentElement.dataset.theme=' + JSON.stringify(theme))
    await window.webContents.debugger.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: touch })
    window.setContentSize(width, height)
    await pause(100)
    await run('document.querySelector(' + JSON.stringify(active + '[data-apply-entry]') + ').scrollIntoView({block:"center"})')
    await capture([width,height,language,theme,'entry'].join('-'))
    await open()
    await capture([width,height,language,theme].join('-'))
  }
  await window.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  window.setContentSize(375, 812)
  await reset('many'); await open()
  await check('large roster search and reduced motion', '!!document.querySelector(".apply-search") && getComputedStyle(document.querySelector(".runtime-apply-dialog")).animationName==="none"')
  await check('long teammate names fit within phone rows', '[...document.querySelectorAll(".apply-target-copy")].every(e=>e.scrollWidth<=e.clientWidth+1)')
  await click('.apply-search'); await window.webContents.insertText('not-a-teammate')
  await check('search retains selected targets', 'document.querySelectorAll(".apply-target").length===0 && !document.querySelector("[data-apply-submit]").disabled')
  await reset('empty'); await open(); await capture('mobile-empty')
  await check('empty roster cannot apply', 'document.querySelector("[data-apply-submit]").disabled')
  await reset('same'); await open()
  await check('matching roster cannot apply redundantly', 'document.querySelectorAll(".apply-target input:disabled").length===3 && document.querySelector("[data-apply-submit]").disabled')
  await reset(); window.setContentSize(1440,920); await window.webContents.debugger.sendCommand('Emulation.setTouchEmulationEnabled', { enabled: false })
  window.webContents.setZoomFactor(2); await pause(120); await open(); await capture('zoom-200')
  assert.deepEqual(errors, [])
  const evidence = { ok: true, checks, consoleErrors: errors, channel: 'isolated Electron; production MembersView; explicit transport fixtures; no Core or Runtime' }
  writeFileSync(join(dirname(userData), 'verification.json'), JSON.stringify(evidence, null, 2))
  console.log(JSON.stringify({ ok: true, checks: checks.length }))
  app.exit(0)
}).catch(async error => {
  console.error(error)
  if (window) writeFileSync(join(dirname(userData), 'failure.png'), (await window.webContents.capturePage()).toPNG())
  app.exit(1)
})
