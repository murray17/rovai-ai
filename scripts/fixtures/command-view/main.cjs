const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { dirname, isAbsolute, join } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(join(userData, 'managed-skill-library'), { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ width: 1040, height: 700, useContentSize: true, show: false,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  await window.loadFile(renderer)
  const run = code => window.webContents.executeJavaScript(code, true)
  const until = async code => {
    for (let attempt = 0; attempt < 150; attempt++) {
      if (await run(code)) return
      await new Promise(resolve => setTimeout(resolve, 20))
    }
    throw new Error(`Timed out: ${code}`)
  }
  await until("!!document.querySelector('.tool-group-summary')")
  assert.equal(await run("document.querySelector('.tool-group-summary').getAttribute('aria-label')"), '已完成 1 个步骤')
  assert.equal(await run("document.querySelectorAll('.tool-call-summary').length"), 0)
  assert.deepEqual(await run('commandViewFixture.reads'), [])
  await run("document.querySelector('.tool-group-summary').click()")
  await until("document.querySelectorAll('.tool-call-summary').length === 1")
  assert.deepEqual(await run('commandViewFixture.reads'), [])
  assert.equal(await run("document.querySelector('.tool-call-disclosure').dataset.executionItemKey"), 'tool:core-1')
  assert.equal(await run("document.querySelector('.tool-call-title').title.endsWith(\"END_OF_BODY'\")"), true)
  assert.equal(await run("getComputedStyle(document.querySelector('.tool-call-title')).textOverflow"), 'ellipsis')
  await run("document.querySelector('.tool-call-summary').click()")
  await until("document.body.textContent.includes('fixture read failure')")
  assert.deepEqual(await run('commandViewFixture.reads'), ['shell-evidence'])
  await run("[...document.querySelectorAll('button')].find(button => button.textContent.includes('重试')).click()")
  await until("document.querySelector('[role=region]')?.textContent === commandViewFixture.expected")
  assert.deepEqual(await run('commandViewFixture.reads'), ['shell-evidence', 'shell-evidence'])
  await until("document.activeElement?.getAttribute('role') === 'region'")
  assert.equal(await run("document.querySelector('[role=region]').scrollHeight > document.querySelector('[role=region]').clientHeight"), true)
  window.webContents.focus()
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'End' })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'End' })
  await until("document.querySelector('[role=region]').scrollTop > 0")
  window.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Escape' })
  window.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Escape' })
  await until("document.activeElement?.classList.contains('tool-call-summary')")
  assert.equal(await run("document.querySelector('.tool-call-disclosure').open"), true)
  for (const [theme, zoom] of [['day', 1], ['night', 2]]) {
    await run(`commandViewFixture.render(${JSON.stringify(theme)})`)
    window.webContents.setZoomFactor(zoom)
    await new Promise(resolve => setTimeout(resolve, 100))
    assert.equal(await run('document.documentElement.scrollWidth > innerWidth'), false)
    assert.equal(await run("getComputedStyle(document.documentElement).colorScheme"), theme === 'night' ? 'dark' : 'light')
    assert.equal(await run("document.querySelector('[role=region]').textContent === commandViewFixture.expected"), true)
    await run("document.querySelector('[role=region]').scrollTop = 0")
    // Hidden Windows windows can return the previous compositor frame on the first capture.
    await window.webContents.capturePage()
    await run('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))')
    writeFileSync(join(dirname(userData), `${theme}.png`), (await window.webContents.capturePage()).toPNG())
  }
  window.webContents.setZoomFactor(1)
  await run('commandViewFixture.showAgent()')
  await until("document.querySelector('.tool-activity-group')?.open === false")
  await run("document.querySelector('.tool-group-summary').click()")
  await until("!!document.querySelector('[data-icon-domain=agent]')")
  await run("document.querySelector('.tool-call-summary').click()")
  await until("document.querySelector('[role=region]')?.textContent === commandViewFixture.agentExpected(0)")
  assert.equal(await run("document.querySelectorAll('.tool-call-detail pre').length"), 1)
  assert.deepEqual(await run('commandViewFixture.reads'), ['shell-evidence', 'shell-evidence'])
  await run("window.retainedResult = document.querySelector('[role=region]'); retainedResult.focus(); retainedResult.scrollTop = 200")
  await run('commandViewFixture.updateAgent(1)')
  await until('commandViewFixture.pendingAgentReads.has(1)')
  assert.equal(await run("document.querySelector('[role=region]') === retainedResult && document.activeElement === retainedResult && retainedResult.scrollTop === 200"), true,
    'inline content must remain mounted and focused while the long report loads')
  await run('commandViewFixture.pendingAgentReads.get(1)()')
  await until("retainedResult.textContent === commandViewFixture.agentExpected(1)")
  await run('commandViewFixture.updateAgent(2)')
  await until('commandViewFixture.pendingAgentReads.has(2)')
  assert.equal(await run("document.activeElement === retainedResult && retainedResult.scrollTop === 200"), true)
  await run('commandViewFixture.updateAgent(3)')
  await until("retainedResult.textContent === commandViewFixture.agentExpected(3)")
  await run('commandViewFixture.pendingAgentReads.get(2)()')
  await new Promise(resolve => setTimeout(resolve, 100))
  assert.equal(await run("document.querySelector('[role=region]') === retainedResult && document.activeElement === retainedResult && retainedResult.scrollTop === 200"), true)
  assert.equal(await run("retainedResult.textContent === commandViewFixture.agentExpected(3)"), true)
  assert.equal(await run("document.querySelector('.tool-call-disclosure').open"), true)
  writeFileSync(join(dirname(userData), 'agent.png'), (await window.webContents.capturePage()).toPNG())
  console.log(JSON.stringify({ ok: true, toolRows: 1, contentReads: 2, originalMultilineContent: true, retry: true, keyboard: true, themes: 2,
    agentIcon: true, sharedDetail: true, inlineToLazy: true, revisionRace: true, preservedFocusAndScroll: true }))
  app.quit()
}).catch(error => { console.error(error); app.exit(1) })
