const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { isAbsolute, join, dirname } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: true, title: 'Rovai quote interaction test', width: 1040, height: 700, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  try {
    await window.loadFile(renderer)
    window.focus()
    window.webContents.focus()
    const report = await window.webContents.executeJavaScript('window.quoteTest.run()', true)
    assert.equal(report.ok, true)
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
    const lastLineTarget = await window.webContents.executeJavaScript('window.quoteTest.lastLineTarget()', true)
    window.webContents.sendInputEvent({ type: 'mouseDown', x: Math.round(lastLineTarget.x), y: Math.round(lastLineTarget.y), button: 'left', clickCount: 3 })
    window.webContents.sendInputEvent({ type: 'mouseUp', x: Math.round(lastLineTarget.x), y: Math.round(lastLineTarget.y), button: 'left', clickCount: 3 })
    await wait(250)
    const lastLine = await window.webContents.executeJavaScript('window.quoteTest.lastLineState()', true)
    assert.equal(lastLine.text, 'same text', 'native triple-click selects the final message line')
    assert.equal(lastLine.candidate, true, 'native final-line selection remains within the message body')
    assert.equal(lastLine.toolbar, true, `native final-line selection exposes the quote toolbar: ${JSON.stringify(lastLine)}`)
    await window.webContents.executeJavaScript("document.dispatchEvent(new Event('copy'))", true)
    await wait(60)
    await window.webContents.executeJavaScript("document.dispatchEvent(new Event('scroll'))", true)
    await wait(60)
    assert.equal((await window.webContents.executeJavaScript('window.quoteTest.lastLineState()', true)).toolbar, false,
      'copy dismissal does not revive a normalized final-line selection on scroll')
    await window.webContents.executeJavaScript('window.quoteTest.clearSelection()', true)
    const target = await window.webContents.executeJavaScript('window.quoteTest.hoverTarget()')
    window.webContents.sendInputEvent({ type: 'mouseMove', x: 2, y: 2 })
    await wait(250)
    window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(target.x), y: Math.round(target.y) })
    await wait(320)
    const hovered = await window.webContents.executeJavaScript('window.quoteTest.hoverState()')
    assert.equal(hovered.open, true, 'native hover opens bubble')
    assert.equal(hovered.triggerFocused, false, 'hover does not move focus')
    window.webContents.sendInputEvent({ type: 'mouseMove', x: Math.round(hovered.x), y: Math.round(hovered.y) })
    await wait(300)
    assert.equal((await window.webContents.executeJavaScript('window.quoteTest.hoverState()')).open, true, 'crossing the gap keeps bubble open')
    for (const theme of ['day', 'night']) {
      assert.equal(await window.webContents.executeJavaScript(`window.quoteTest.theme('${theme}')`, true), true)
      writeFileSync(join(dirname(userData), `${theme}.png`), (await window.webContents.capturePage()).toPNG())
    }
    window.webContents.sendInputEvent({ type: 'mouseMove', x: 2, y: 2 })
    await wait(300)
    assert.equal((await window.webContents.executeJavaScript('window.quoteTest.hoverState()')).open, false, 'leaving closes bubble')
    for (const theme of ['day', 'night']) {
      await window.webContents.executeJavaScript(`window.quoteTest.theme('${theme}')`, true)
      await window.webContents.executeJavaScript('window.quoteTest.linePreview()', true)
      await wait(350)
      writeFileSync(join(dirname(userData), `lines-${theme}.png`), (await window.webContents.capturePage()).toPNG())
    }
    window.webContents.setZoomFactor(2)
    assert.equal(await window.webContents.executeJavaScript("window.quoteTest.theme('day')", true), true)
    console.log(JSON.stringify(report))
    app.exit(0)
  } catch (error) { console.error(error); app.exit(1) }
})
