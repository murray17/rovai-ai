const assert = require('node:assert/strict')
const { mkdirSync, writeFileSync } = require('node:fs')
const { dirname, isAbsolute, join } = require('node:path')
const { app, BrowserWindow } = require('electron')
const [renderer, userData] = process.argv.slice(2)
assert.ok(isAbsolute(renderer) && isAbsolute(userData))
mkdirSync(userData, { recursive: true })
app.setPath('userData', userData)
app.setPath('sessionData', join(userData, 'session'))
const wait = ms => new Promise(resolve => setTimeout(resolve, ms))
app.whenReady().then(async () => {
  const window = new BrowserWindow({ show: false, width: 1040, height: 700, useContentSize: true,
    webPreferences: { contextIsolation: true, sandbox: true, nodeIntegration: false, backgroundThrottling: false } })
  window.webContents.on('console-message', event => console.error(event.message))
  const run = code => window.webContents.executeJavaScript(code, true)
  const state = async () => { await wait(180); return run('window.notificationTest.state()') }
  const click = async selector => {
    const point = await run(`(() => { const r = document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect(); return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + r.height / 2) } })()`)
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    window.webContents.sendInputEvent({ type: 'mouseDown', ...point, button: 'left', clickCount: 1 })
    window.webContents.sendInputEvent({ type: 'mouseUp', ...point, button: 'left', clickCount: 1 })
    return state()
  }
  const awayMouse = () => window.webContents.sendInputEvent({ type: 'mouseMove', x: 10, y: 600 })
  const capture = async name => writeFileSync(join(dirname(userData), `${name}.png`), (await window.webContents.capturePage()).toPNG())
  try {
    await window.loadFile(renderer)
    window.webContents.focus()
    await state()
    await run("document.querySelector('#draft').focus(); window.notificationTest.source(null)")
    await state()
    await run("window.notificationTest.admit('turn_completed')")
    let current = await state()
    assert.equal(current.cards.length, 0)
    assert.equal(current.acknowledgements.length, 0, 'Reading old messages suppresses completion without marking it read')
    await run('window.notificationTest.away()')
    assert.equal((await state()).cards.length, 0, 'A suppressed completion cannot replay on leaving')
    await run("window.notificationTest.admit('turn_completed', 'private-original')")
    current = await state()
    assert.equal(current.cards.length, 1)
    assert.equal(current.cards[0].message, '本轮已完成')
    assert.match(current.cards[0].source, /与洛克单聊$/)
    assert.equal(current.cards[0].width, 340)
    assert.equal(current.focused, 'draft', 'Admission cannot steal focus')
    assert.equal(current.overflow, false)
    // Hidden windows may defer their first animation frame until capture.
    await run('document.getAnimations().forEach(animation => animation.finish())')
    await capture('notification-day')
    await run("document.documentElement.dataset.theme = 'night'")
    await capture('notification-night')
    current = await click('.notification-heads-up-open')
    assert.equal(current.navigations[0].singleChat.conversationId, 'private-original')
    assert.equal(current.navigations[0].singleChat.agentRunId, 'private-run')
    assert.equal(current.acknowledgements.length, 1)
    awayMouse()
    await run("window.notificationTest.source('private-original'); window.notificationTest.admit('turn_completed', 'private-original')")
    assert.equal((await state()).cards.length, 0)
    await run("window.notificationTest.admit('turn_completed', 'private-other')")
    assert.equal((await state()).cards.length, 0, 'The attentive Camp is quiet across its public and private reading surfaces')
    await run('window.notificationTest.away()')
    assert.equal((await state()).cards.length, 0, 'A reminder suppressed in the current Camp cannot replay after leaving')
    awayMouse()
    await run("window.notificationTest.attentive(false); window.notificationTest.admit('turn_failed', 'private-original')")
    assert.equal((await state()).cards.length, 0)
    await run("window.notificationTest.source('private-original', true, true); window.notificationTest.attentive(true)")
    assert.equal((await state()).cards.length, 0, 'Returning to an already visible exact failure is quiet')
    await run("window.notificationTest.away(); window.notificationTest.admit('approval_pending', null, 'shared-round'); window.notificationTest.admit('turn_completed', null, 'shared-round')")
    current = await state()
    assert.equal(current.cards.length, 1)
    assert.equal(current.cards[0].message, '有操作等待你审批', 'Completion cannot replace a pending approval')
    current = await click('.notification-heads-up-close')
    assert.equal(current.cards.length, 1)
    assert.equal(current.cards[0].summary, true, 'The remaining queue needs explicit advance')
    current = await click('.notification-heads-up-open')
    assert.equal(current.cards[0].message, '本轮已完成')
    await click('.notification-heads-up-close')
    awayMouse()
    // Independent hover and focus pauses preserve elapsed time, and moving out cannot undo focus pause.
    await run("window.notificationTest.admit('turn_completed', 'lifetime')")
    await state()
    await wait(1_600)
    const point = await run("(() => { const r = document.querySelector('.notification-heads-up-open').getBoundingClientRect(); return { x: Math.round(r.x+20), y: Math.round(r.y+20) } })()")
    window.webContents.sendInputEvent({ type: 'mouseMove', ...point })
    await run("document.querySelector('.notification-heads-up-open').focus()")
    await wait(100)
    assert.equal(await run("document.activeElement === document.querySelector('.notification-heads-up-open')"), true, 'Keyboard focus reached the card')
    awayMouse()
    await wait(8_200)
    assert.equal((await state()).cards.length, 1, 'Focus pause survives pointer leave')
    await run("document.querySelector('#draft').focus()")
    await wait(6_650)
    assert.equal((await state()).cards.length, 0, 'Resume uses the remaining duration, not a fresh eight seconds')
    await run("window.notificationTest.attentive(false); window.notificationTest.admit('turn_completed', 'invalidated')")
    await state()
    await run("window.notificationTest.invalidate('occurrence-9'); window.notificationTest.attentive(true)")
    assert.equal((await state()).cards.length, 0, 'Background invalidation is reconciled before display')
    await run("window.notificationTest.admit('turn_completed', 'long-name', 'focus-round', '名称很长的队员'.repeat(12))")
    await state()
    assert.equal(await run(`(() => {
      const card = document.querySelector('.notification-heads-up')
      const source = card.querySelector('strong')
      return source.scrollWidth <= source.clientWidth && card.scrollWidth <= card.clientWidth
    })()`), true, 'Long Camp and member names stay within the card')
    await run("window.retainedNotification = document.querySelector('.notification-heads-up-open'); window.retainedNotification.focus(); window.notificationTest.admit('approval_pending', 'long-name', 'focus-round')")
    await state()
    assert.equal(await run("document.activeElement === window.retainedNotification && window.retainedNotification === document.querySelector('.notification-heads-up-open')"), true,
      'Updating the same source keeps its DOM identity and keyboard focus')

    // Exercise the production settings component, including persisted filters and failed-save recovery.
    await run("window.notificationTest.settings(true); document.documentElement.dataset.theme = 'day'")
    await state()
    assert.equal(await run("document.querySelectorAll('[role=switch]').length"), 9)
    const groups = await run("[...document.querySelectorAll('.notification-scenario-heading h3')].map(node => node.textContent)")
    assert.deepEqual(groups, ['会话', '使命', '任务'])
    await click('[data-notification-preference="taskStatusHeadsUpEnabled"]')
    assert.equal((await run('window.notificationTest.preference()')).taskStatusHeadsUpEnabled, true)
    await click('[data-notification-preference="taskStatuses"]')
    await click('.notification-scenario-task .notification-filter-options label:first-child input')
    assert.deepEqual((await run('window.notificationTest.preference()')).taskStatuses, ['blocked', 'cancelled'])
    assert.equal(await run('document.activeElement?.dataset.notificationPreference'), 'taskStatuses:completed')
    await run('window.notificationTest.failPreferenceSave()')
    await click('[data-notification-preference="taskStatuses:in_progress"]')
    assert.match(await run("document.querySelector('[role=alert]').textContent"), /测试保存失败/)
    assert.equal(await run('document.activeElement?.dataset.notificationPreference'), 'taskStatuses:in_progress')
    assert.deepEqual((await run('window.notificationTest.preference()')).taskStatuses, ['blocked', 'cancelled'])
    await click('.notification-settings-error button')
    assert.equal(await run('document.activeElement?.dataset.notificationPreference'), 'taskStatuses:in_progress')
    assert.deepEqual((await run('window.notificationTest.preference()')).taskStatuses, ['blocked', 'cancelled', 'in_progress'])
    await click('[data-notification-preference="taskStatuses:in_progress"]')
    await run('window.notificationTest.failPreferenceSave()')
    await click('[data-notification-preference="singleChatHeadsUpEnabled"]')
    assert.match(await run("document.querySelector('[role=alert]').textContent"), /测试保存失败/)
    assert.equal(await run("document.querySelector('[data-notification-preference=singleChatHeadsUpEnabled]').checked"), true)
    await click('.notification-settings-error button')
    assert.equal((await run('window.notificationTest.preference()')).singleChatHeadsUpEnabled, false)
    await capture('notification-settings-day')
    await run("document.documentElement.dataset.theme = 'night'")
    await state()
    await capture('notification-settings-night')
    window.setContentSize(760, 820)
    await state()
    assert.equal(await run('document.documentElement.scrollWidth > innerWidth'), false)
    const stacked = await run("[...document.querySelectorAll('.notification-scenario')].map(node => Math.round(node.getBoundingClientRect().left))")
    assert.equal(new Set(stacked).size, 1)
    await capture('notification-settings-narrow')
    const retainedPreference = await run('window.notificationTest.preference()')
    await run('window.notificationTest.tasks(false)')
    await state()
    assert.deepEqual(await run("[...document.querySelectorAll('.notification-scenario-heading h3')].map(node => node.textContent)"), ['会话', '使命'])
    await capture('notification-settings-tasks-off')
    await run('window.notificationTest.tasks(true)')
    await state()
    assert.deepEqual(await run('window.notificationTest.preference()'), retainedPreference, 'Capability must not overwrite notification preferences')
    await run('window.notificationTest.settings(false)')
    await state()
    await run("window.notificationTest.admit('task_status_changed')")
    current = await state()
    assert.equal(current.cards.length, 1)
    assert.match(current.cards[0].message, /验收任务/)
    await run('window.notificationTest.tasks(false)')
    assert.equal((await state()).cards.length, 0, 'Disabling removes queued Task reminders')
    await run('window.notificationTest.tasks(true)')
    assert.equal((await state()).cards.length, 0, 'Enabling must not replay historical Task reminders')
    await run("window.notificationTest.admit('turn_completed')")
    assert.equal((await state()).cards[0].message, '本轮已完成')
    await run('window.notificationTest.tasks(false)')
    assert.equal((await state()).cards[0].message, '本轮已完成', 'Task capability preserves unrelated queued reminders')
    await run('window.notificationTest.tasks(true)')
    assert.equal((await state()).cards[0].message, '本轮已完成')

    await click('.notification-heads-up-open')
    await run("window.notificationTest.admit('turn_completed'); window.notificationTest.tasks(false)")
    assert.equal((await state()).cards[0]?.message, '本轮已完成', 'Disabling must consume unrelated changes that were not polled yet')
    await click('.notification-heads-up-open')
    await run("window.notificationTest.admit('task_status_changed', null, undefined, undefined, false); window.notificationTest.admit('turn_completed'); window.notificationTest.tasks(true)")
    assert.equal((await state()).cards[0]?.message, '本轮已完成', 'Enabling must consume unrelated changes that were not polled yet')
    await click('.notification-heads-up-open')
    assert.equal((await state()).cards.length, 0, 'Historical Task signals cannot enter the overflow queue during re-enablement')
    await run("window.notificationTest.admit('task_status_changed')")
    assert.match((await state()).cards[0]?.message, /验收任务/, 'New Task signals are still admitted')
    await run('window.notificationTest.tasks(false)')
    assert.equal((await state()).cards.length, 0)
    // Keep an actual unread refresh pending while toggling. No Task-only read may
    // hold the global poll or delay ordinary reminders, even after Task is off.
    await run("window.notificationTest.admit('turn_completed')")
    await state()
    await run('window.notificationTest.holdInbox()')
    await click('.notification-heads-up-open')
    assert.ok((await state()).pendingInbox > 0, 'Unread refresh is really pending')
    await run("window.notificationTest.tasks(true); window.notificationTest.admit('turn_completed')")
    assert.equal((await state()).cards[0]?.message, '本轮已完成', 'A pending Task/inbox watermark cannot block an ordinary batch')
    await run('window.notificationTest.tasks(false)')
    assert.equal((await state()).cards[0]?.message, '本轮已完成', 'Disabling cannot leave the ordinary batch awaiting the old Promise')
    await click('.notification-heads-up-open')
    await run('window.notificationTest.releaseInbox()')
    assert.equal((await state()).cards.length, 0)

    // Old Task is before the settings transaction; both new signals are after it.
    // Failing every inbox read cannot swallow the new Task or move that boundary.
    await run("window.notificationTest.admit('task_status_changed', null, 'old-failure-task', undefined, false); window.notificationTest.failInboxReads(10); window.notificationTest.tasks(true); window.notificationTest.admit('turn_completed'); window.failureWindowTask = window.notificationTest.admit('task_status_changed')")
    assert.equal((await state()).cards[0]?.message, '本轮已完成')
    await click('.notification-heads-up-open')
    assert.ok((await state()).failedInboxReads < 10, 'An inbox request actually failed')
    await run('window.notificationTest.failInboxReads(0); window.notificationTest.poll()')
    assert.equal((await state()).cards[0]?.summary, true)
    await click('.notification-heads-up-open')
    assert.match((await state()).cards[0]?.message, /验收任务/, 'The Task generated during the failure window is retained')
    await click('.notification-heads-up-open')
    assert.equal(await run('window.notificationTest.state().acknowledgements.at(-1).request.command.acknowledgementId'), await run('window.failureWindowTask'))
    await run('window.notificationTest.poll()')
    assert.equal((await state()).cards.length, 0, 'New Task appears once; old Task never enters overflow')

    // A delayed read sees a later global waterline, but cannot redefine enablement.
    await run("window.notificationTest.tasks(false); window.notificationTest.admit('turn_completed')")
    await state()
    await run('window.notificationTest.holdInbox()')
    await click('.notification-heads-up-open')
    assert.ok((await state()).pendingInbox > 0)
    await run("window.notificationTest.admit('task_status_changed', null, 'old-delayed-task', undefined, false); window.notificationTest.tasks(true); window.delayedWindowTask = window.notificationTest.admit('task_status_changed')")
    assert.match((await state()).cards[0]?.message, /验收任务/, 'New Task is processed before the delayed inbox response')
    await run('window.notificationTest.releaseInbox(); window.notificationTest.tasks(true); window.notificationTest.poll()')
    await state()
    await click('.notification-heads-up-open')
    assert.equal(await run('window.notificationTest.state().acknowledgements.at(-1).request.command.acknowledgementId'), await run('window.delayedWindowTask'))
    assert.equal((await state()).cards.length, 0, 'Late reads and same-value saves cannot replay old Tasks')

    await run("window.notificationTest.admit('task_status_changed')")
    assert.match((await state()).cards[0]?.message, /验收任务/)
    await run('window.notificationTest.tasks(false); window.notificationTest.tasks(true)')
    assert.equal((await state()).cards.length, 0, 'A new boundary clears old queued Tasks even when React batches off/on')

    // The notification response owns its capability snapshot. A settings read can
    // stay pending or fail while both ordinary and new Task signals are consumed.
    for (const mode of ['pending', 'late-failure', 'failed']) {
      await run('window.notificationTest.tasks(false)')
      await state()
      await run(`window.notificationTest.admit('task_status_changed', null, 'before-${mode}', undefined, false);
        ${mode === 'failed' ? 'window.notificationTest.failTaskReads(1)' : 'window.notificationTest.holdTaskReads()'};
        window.notificationTest.tasks(true)`)
      current = await state()
      if (mode === 'failed') assert.equal(current.failedTaskReads, 0, 'The capability request really failed')
      else assert.ok(current.pendingTaskReads > 0, 'The capability request is really pending')
      await run("window.notificationTest.admit('turn_completed'); window.capabilityWindowTask = window.notificationTest.admit('task_status_changed')")
      current = await state()
      assert.equal(current.cards[0]?.message, '本轮已完成', `${mode}: ordinary reminders do not wait for settings`)
      await click('.notification-heads-up-open')
      assert.equal((await state()).cards[0]?.summary, true, `${mode}: the new Task was queued before settings returned`)
      await click('.notification-heads-up-open')
      assert.match((await state()).cards[0]?.message, /验收任务/)
      await click('.notification-heads-up-open')
      await run(`window.notificationTest.releaseTaskReads(${mode === 'late-failure'}); window.notificationTest.poll()`)
      current = await state()
      const acknowledgementId = await run('window.capabilityWindowTask')
      assert.equal(current.acknowledgements.filter(item => item.request.command.acknowledgementId === acknowledgementId).length, 1,
        `${mode}: the exact Task is acknowledged once`)
      assert.equal(current.cards.length, 0, `${mode}: old Task is not replayed`)
      assert.deepEqual(current.taskCapability, { enabled: true, ready: true, error: null }, `${mode}: late failure cannot erase the batch snapshot`)
    }

    // A settings response captured while disabled must not overwrite a newer
    // notification snapshot. Release the stale disabled response on its own.
    await run('window.notificationTest.tasks(false)')
    await state()
    await run('window.notificationTest.holdTaskReads(); window.notificationTest.tasks(false); window.notificationTest.tasks(true)')
    await state()
    await run("window.notificationTest.admit('task_status_changed')")
    assert.match((await state()).cards[0]?.message, /验收任务/)
    await run('window.notificationTest.releaseTaskRead()')
    assert.equal((await state()).taskCapability.enabled, true)
    assert.match((await state()).cards[0]?.message, /验收任务/, 'A stale disabled settings response cannot discard the queued Task')
    await run('window.notificationTest.releaseTaskReads()')
    await click('.notification-heads-up-open')

    // Capture an enabled batch, then confirm disable without any intervening
    // notification. The late batch must not re-enable Tasks or lose ordinary work.
    await run("window.notificationTest.holdChanges(); window.notificationTest.admit('task_status_changed'); window.notificationTest.admit('turn_completed')")
    assert.ok((await state()).pendingChanges > 0)
    await run('window.notificationTest.tasks(false)')
    assert.equal((await state()).taskCapability.enabled, false)
    await run('window.notificationTest.releaseChanges()')
    current = await state()
    assert.equal(current.cards[0]?.message, '本轮已完成')
    assert.equal(current.taskCapability.enabled, false, 'An old enabled batch cannot undo a newer confirmed disable')
    await click('.notification-heads-up-open')
    assert.equal((await state()).cards.length, 0, 'The late Task is not queued')
    const idleReads = (await state()).changeReads
    assert.ok((await state()).changeReads - idleReads <= 1, 'An unchanged snapshot cannot create a render/poll loop')

    for (const fail of [false, true]) {
      await run('window.taskCapabilityTest.start()')
      await state()
      await run('window.taskCapabilityTest.save()')
      await state()
      assert.equal((await run('window.taskCapabilityTest.state()')).saving, true)
      await run('window.taskCapabilityTest.switchHost()')
      await state()
      const expected = { enabled: false, ready: true, saving: false, error: null, draftRetained: true }
      assert.deepEqual(await run('window.taskCapabilityTest.state()'), expected, 'New Host resets all local preference state without remounting the draft')
      await run(`window.taskCapabilityTest.settle(${fail})`)
      await state()
      assert.deepEqual(await run('window.taskCapabilityTest.state()'), expected, 'Old Host success/failure must not modify new Host state')
    }
    await run('window.taskCapabilityTest.start()')
    await state()
    await run('window.taskCapabilityTest.save()')
    await state()
    await run('window.taskCapabilityTest.switchHost()')
    await state()
    await run('window.taskCapabilityTest.returnToHost()')
    await state()
    await run('window.taskCapabilityTest.settle(true)')
    await state()
    assert.deepEqual(await run('window.taskCapabilityTest.state()'),
      { enabled: true, ready: true, saving: false, error: null, draftRetained: true },
      'Returning to the same client object cannot revive an earlier Host visit failure')
    // Runtime questions share the real approval queue and lifetime without durable acknowledgements.
    await run("window.notificationTest.away(); document.documentElement.dataset.theme = 'day'")
    await state()
    const beforeNativeAcks = (await state()).acknowledgements.length
    await run("window.notificationTest.admit('approval_pending'); window.notificationTest.native('native-a'); window.notificationTest.native('native-b','private-native')")
    current = await state()
    assert.equal(current.cards[0]?.message, '有操作等待你审批')
    await click('.notification-heads-up-close')
    assert.match((await state()).cards[0]?.text, /还有 2 条提醒/)
    await click('.notification-heads-up-open')
    assert.equal((await state()).cards[0]?.message, '爱丽丝在等你回答')
    assert.equal(await run("getComputedStyle(document.querySelector('.notification-heads-up-dot')).backgroundColor"), 'rgb(22, 131, 255)')
    await capture('native-question-notification-day')
    await click('.notification-heads-up-open')
    current = await state()
    assert.equal(current.navigations.at(-1).interactionId, 'native-a')
    assert.equal(current.navigations.at(-1).kind, 'open_native_interaction')
    assert.equal(current.acknowledgements.length, beforeNativeAcks, 'A native question never writes a durable approval acknowledgement')
    await click('.notification-heads-up-open')
    assert.match((await state()).cards[0]?.source, /与爱丽丝单聊$/)
    await run("document.documentElement.dataset.theme = 'night'")
    assert.equal(await run("getComputedStyle(document.querySelector('.notification-heads-up-dot')).backgroundColor"), 'rgb(90, 167, 255)')
    await capture('native-question-notification-night')
    await click('.notification-heads-up-open')
    assert.equal((await state()).navigations.at(-1).singleChat.conversationId, 'private-native')
    await run("window.notificationTest.native('native-expiry',null,Date.now()+500)")
    assert.equal((await state()).cards[0]?.message, '爱丽丝在等你回答')
    await wait(550)
    assert.equal((await state()).cards.length, 0, 'Deadline removes queued Runtime attention without an answer')
    await run("window.notificationTest.native('native-resolved')")
    assert.equal((await state()).cards.length, 1)
    await run("window.notificationTest.resolveNative('native-resolved')")
    assert.equal((await state()).cards.length, 0, 'Another surface resolving the source removes its notification')
    await run("window.notificationTest.native('native-old')")
    assert.equal((await state()).cards.length, 1)
    await run('window.notificationTest.refresh()')
    assert.equal((await state()).cards.length, 0, 'Reload establishes a Runtime baseline without replaying existing questions')
    await run("window.notificationTest.source(null); window.notificationTest.native('native-quiet')")
    assert.equal((await state()).cards.length, 0, 'The active Thread remains quiet for questions too')
    await run('window.notificationTest.away()')
    assert.equal((await state()).cards.length, 0, 'A quiet native source cannot replay on leaving')
    console.log(JSON.stringify({ ok: true }))
    app.exit(0)
  } catch (error) { console.error(error); app.exit(1) }
})
